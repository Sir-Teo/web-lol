"""Normalize mana and cooldown rank indexing against game and client records."""
import hashlib
import json
from pathlib import Path
pin = json.loads(Path('docs/reference/ashe-spell-ranks.json').read_text())
game_raw = Path('.cache/ashe-16.18.json').read_bytes()
client_raw = Path('.cache/ashe-client-16.18.json').read_bytes()
assert hashlib.sha256(game_raw).hexdigest() == pin['gameSha256']
assert hashlib.sha256(client_raw).hexdigest() == pin['clientSha256']
game, client = json.loads(game_raw), json.loads(client_raw)
result = {}
for index, (key, count) in enumerate([('q', 5), ('w', 5), ('e', 5), ('r', 3)]):
    record = pin['spells'][key]
    assert game[pin['root']]['spells'][index] == record['path']
    spell = game[record['path']]['mSpell']
    assert spell['cooldownTime'] == record['cooldownTime']
    assert spell.get('mana') == record['mana']
    for field, value in record['client'].items():
        assert client['spells'][index][field] == value
    costs = record['mana'][:count] if record['mana'] else [0] * count
    cooldowns = record['cooldownTime'][1:count + 1]
    assert costs == record['client']['costCoefficients'][:count]
    assert cooldowns == record['client']['cooldownCoefficients'][:count]
    result[key] = {'manaByRank': costs, 'cooldownSecondsByRank': cooldowns}
Path('src/content/ashe-spell-ranks.ts').write_text('// Generated by tools/assets/export-ashe-spell-ranks.py.\nexport const ASHE_SPELL_RANKS = ' + json.dumps(result, indent=2) + ' as const;\n')
print('Verified Q/W/E/R mana and cooldown indexing against both source exports')
