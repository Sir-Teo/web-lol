"""Verify spellbook selection and Volley records, then export normal rank values."""
import hashlib
import json
from pathlib import Path

pin = json.loads(Path('docs/reference/ashe-w.json').read_text())
raw = Path('.cache/ashe-16.18.json').read_bytes()
assert hashlib.sha256(raw).hexdigest() == pin['sha256']
source = json.loads(raw)
assert source[pin['root']]['spells'][pin['spellIndex']] == pin['spell']
for key, record in pin['records'].items():
    assert source[key] == record
spell = source[pin['spell']]['mSpell']
data = {}
for name, field in [('BaseDamage', 'baseDamageByRank'), ('NumberOfArrowsTooltip', 'arrowsByRank'), ('ADRatio', 'bonusADRatioByRank')]:
    values = next(v['values'] for v in spell['DataValues'] if v['name'] == name)
    data[field] = values[1:6]
speeds = [r['mSpell']['mMissileSpec']['movementComponent']['mSpeed']
          for k, r in pin['records'].items() if k != pin['spell']]
assert len(set(speeds)) == 1
data['projectileSpeed'] = speeds[0]
Path('src/content/ashe-w.ts').write_text(
    '// Generated by tools/assets/export-ashe-w.py.\n'
    + 'export const ASHE_W = ' + json.dumps(data, indent=2) + ' as const;\n')
print('Verified spellbook-selected Volley and projectile records')
