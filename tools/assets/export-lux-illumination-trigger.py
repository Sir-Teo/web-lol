"""Generate playback profiles only after complete BIN/shared-texture verification."""
import json
from pathlib import Path
import runpy

verified = runpy.run_path('tools/assets/verify-lux-illumination-trigger.py')
assert verified['record'] == verified['pin']['definition']
emitters, pin = verified['emitters'], verified['pin']

def vector(v):
    return v if isinstance(v, list) else [v]

def birth(value, fallback):
    dynamics = value.get('dynamics')
    if dynamics:
        assert dynamics['times'] == [0] and len(dynamics['values']) == 1
    base = vector(dynamics['values'][0] if dynamics else value.get('constantValue', fallback))
    tables = dynamics.get('probabilityTables') if dynamics else None
    return {'value': base, 'probabilities': [
        {'single': t.get('singleValue', 1), 'times': t.get('keyTimes', []), 'values': t.get('keyValues', [])}
        for t in tables] if tables is not None else None}

def curve(value, fallback):
    dynamics = value.get('dynamics')
    if dynamics:
        # Only identity probability tables occur on these lifetime curves.
        for t in dynamics.get('probabilityTables', []):
            assert not t.get('keyTimes') and not t.get('keyValues') and t.get('singleValue', 1) == 1
        return {'times': dynamics['times'], 'values': [vector(v) for v in dynamics['values']]}
    base = vector(value.get('constantValue', fallback))
    return {'times': [0, 1], 'values': [base, base]}

textures = {t['path']: t['output'].removeprefix('public/') for t in pin['textures']}
profiles = []
for index, e in enumerate(emitters):
    shape = e.get('SpawnShape', {})
    offset = shape.get('emitOffset', [0, 0, 0])
    offset = offset if isinstance(offset, dict) else {'constantValue': offset}
    palette = e.get('paletteDefinition')
    profiles.append({
        'index': index, 'name': e['emitterName'],
        'rate': e['rate']['constantValue'], 'single': bool(e.get('isSingleParticle', False)),
        'emitterLife': e['lifetime'], 'emitterLinger': e.get('emitterLinger'), 'particleLinger': e.get('particleLinger'),
        'life': birth(e['particleLifetime'], 3),
        'size': birth(e['birthScale0'], [1, 1, 1]),
        'rotation': birth(e.get('birthRotation0', {}), [0, 0, 0]),
        'velocity': birth(e.get('birthVelocity', {}), [0, 0, 0]),
        'orbitalVelocity': birth(e.get('birthOrbitalVelocity', {}), [0, 0, 0]),
        'drag': birth(e.get('birthDrag', {}), [0, 0, 0]),
        'emitterPosition': birth(e.get('EmitterPosition', {}), [0, 0, 0]),
        'spawnOffset': birth(offset, [0, 0, 0]),
        'spawnAngles': [birth(v, 0) for v in shape.get('emitRotationAngles', [])],
        'spawnAxes': shape.get('emitRotationAxes', []),
        'worldAcceleration': curve(e.get('worldAcceleration', {}), [0, 0, 0]),
        'bind': curve(e.get('bindWeight', {}), 0),
        'scale': curve(e.get('scale0', {}), [1, 1, 1]),
        'birthColor': birth(e.get('birthColor', {}), [1, 1, 1, 1]),
        'color': curve(e.get('Color', {}), [1, 1, 1, 1]),
        'uniform': bool(e.get('isUniformScale', False)),
        'directionOriented': bool(e.get('isDirectionOriented', False)),
        'directionScale': e.get('{7ad984a5}', 0), 'directionMin': e.get('{ebd44083}', 1),
        'localOrientation': bool(e.get('isLocalOrientation', True)),
        'primitive': 'ray' if 'primitive' in e else 'cameraQuad',
        'pass': e.get('pass', 0), 'blend': e.get('blendMode', 0), 'miscRenderFlags': e.get('miscRenderFlags', 0),
        'texture': textures[e['texture'].lower()],
        'lookup': textures[e['particleColorTexture'].lower()] if 'particleColorTexture' in e else None,
        'lookupScales': e.get('colorLookUpScales', [1, 1]), 'lookupOffsets': e.get('colorLookUpOffsets', [0, 0]),
        'lookupTypes': [e.get('colorLookUpTypeX', 1), e.get('colorLookUpTypeY', 0)],
        'atlas': {'grid': e.get('texDiv', [1, 1]), 'frames': e.get('numFrames', 1), 'start': e.get('startFrame', 0), 'rate': e.get('frameRate', 0)},
        'palette': {'texture': textures[palette['paletteTexture'].lower()], 'count': palette['paletteCount'],
            'selector': birth(palette['paletteSelector'], [0, 0, 0]),
            'mix': birth(palette['palleteSrcMixColor'], [0, 0, 0, 0])} if palette else None,
        'unresolvedOuterRing': e.get('{4ffce322}'),
    })
Path('src/content/lux-illumination-trigger-vfx.ts').write_text(
    '// Generated by tools/assets/export-lux-illumination-trigger.py.\n' +
    '// Unresolved fields remain in the complete source audit; this is not native playback certification.\n' +
    'export const LUX_ILLUMINATION_TRIGGER_VFX = ' + json.dumps(profiles, indent=2) + ' as const;\n')
print('Generated all five detonation profiles with separate birth and lifetime curves.')
