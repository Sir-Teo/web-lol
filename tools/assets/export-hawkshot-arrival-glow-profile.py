"""Export verified endpoint glow parameters and the exact raw color-ramp samples."""
from pathlib import Path
import json,hashlib
p=json.loads(Path('docs/reference/hawkshot-arrival-glows.json').read_text())
assert hashlib.sha256(Path('docs/reference/hawkshot-effects.json').read_bytes()).hexdigest()==p['definitionsSha256']
layers=[]
for e in p['emitters']:
    layers.append(dict(name=e['emitterName'],rate=e['rate']['constantValue'],duration=e['lifetime'],life=e['particleLifetime']['constantValue'],
        scale=e['birthScale0']['constantValue'][0],scaleRange=e['birthScale0']['dynamics']['probabilityTables'][0]['keyValues'],
        offset=e['EmitterPosition']['constantValue'],color=e['Color']['constantValue'],rotation=e['birthRotation0']['constantValue']))
Path('src/content/hawkshot-arrival-glows.ts').write_text('// Generated by tools/assets/export-hawkshot-arrival-glow-profile.py.\nexport const ARRIVAL_GLOWS = '+json.dumps(layers,indent=2)+' as const;\nexport const ARRIVAL_GLOW_RAMP = '+json.dumps(p['ramp']['rgba8Samples'])+' as const;\n')
print('Exported endpoint glow profiles and exact 64-sample RGB ramp')
