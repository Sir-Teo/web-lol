"""Verify selected standard Rift constants against the pinned map, then export."""
import hashlib
import json
from pathlib import Path

pin = json.loads(Path('docs/reference/ambient-gold.json').read_text())
raw = Path('.cache/map11-definition.json').read_bytes()
assert hashlib.sha256(raw).hexdigest() == pin['sha256']
source = json.loads(raw)
key = source[pin['mode']]['mGameModeConstants']
assert key == pin['constantsRecord']
fields = {name: value for group in source[key]['mGroups'].values()
          for name, value in group.get('mConstants', {}).items() if 'AmbientGold' in name}
assert fields == pin['fields']
data = {
    'startSeconds': fields['mission_AmbientGoldStartTime']['mValue'],
    'amount': round(fields['ai_AmbientGoldAmount']['mValue'], 6),
    'intervalSeconds': fields['ai_AmbientGoldInterval']['mValue'],
}
Path('src/content/ambient-gold.ts').write_text(
    '// Generated by tools/assets/export-ambient-gold.py; original floats retained in the reference pin.\n'
    + 'export const AMBIENT_GOLD = ' + json.dumps(data, indent=2) + ' as const;\n')
print('Verified CLASSIC mode reference and exported ambient gold constants')
