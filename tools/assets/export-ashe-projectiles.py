"""Verify ordinary and empowered attack projectile records against pinned source."""
import hashlib
import json
from pathlib import Path

pin = json.loads(Path('docs/reference/ashe-attack-projectiles.json').read_text())
raw = Path('.cache/ashe-16.18.json').read_bytes()
assert hashlib.sha256(raw).hexdigest() == pin['sha256']
source = json.loads(raw)
speeds = []
for key, record in pin['records'].items():
    assert source[key] == record
    movement = record['mSpell']['mMissileSpec']['movementComponent']
    assert movement['__type'] == 'FixedSpeedMovement'
    speeds.append(movement['mSpeed'])
assert len(speeds) == 4 and len(set(speeds)) == 1
Path('src/content/ashe-projectiles.ts').write_text(
    '// Generated by tools/assets/export-ashe-projectiles.py.\n'
    + 'export const ASHE_ATTACK_PROJECTILE_SPEED = ' + str(speeds[0]) + ';\n')
print('Verified four Ashe attack records and exported their shared projectile speed')
