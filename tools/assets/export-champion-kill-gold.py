"""Export base champion gold; do not infer shutdown/devaluation fields."""
import hashlib
import json
from pathlib import Path

# This existing pin retains the complete standard-mode bounty configuration.
pin = json.loads(Path('docs/reference/assist-window.json').read_text())
raw = Path('.cache/map11-definition.json').read_bytes()
assert hashlib.sha256(raw).hexdigest() == pin['sha256']
source = json.loads(raw)
assert pin['config'] in source[pin['mode']]['Configs']
assert source[pin['config']] == pin['record']
values = pin['record']['BaseGold']
# Independently corroborated by official 25.09 Champion Bounties / Tuning.
assert values == [300 + max(0, level - 6) * 10 for level in range(1, 19)]
Path('src/content/champion-kill-gold.ts').write_text(
    '// Generated by tools/assets/export-champion-kill-gold.py.\n'
    '// Standard-mode BaseGold by victim level, before bounty modifiers.\n'
    + 'export const CHAMPION_BASE_KILL_GOLD = [\n  '
    + ', '.join(str(int(value)) for value in values) + ',\n] as const;\n')
print('Verified champion base kill gold for levels 1–18')
