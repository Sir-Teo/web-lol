"""Export selected pinned champion and global growth fields into the simulation bundle."""
import json
import hashlib
from pathlib import Path

raw = Path('docs/reference/ashe-progression.json').read_bytes()
assert hashlib.sha256(raw).hexdigest() == '8f92b1cfbb306f35f1a6555e41518fe141f1cceeee03bc4f0b7a9f4d0ccab512'
pin = json.loads(raw)
record = pin['sources'][0]['records']['Characters/Ashe/CharacterRecords/Root']
factors = pin['sources'][1]['records']['{45e9cf65}']['mPerLevelStatsFactor']
def value(key):
    return round(record[key]['baseValue'], 6)
resource = record['primaryAbilityResource']
data = {
    'hp': value('baseHPModifiable'), 'hpGrowth': value('hpPerLevelModifiable'),
    'mana': round(resource['{726ee5cd}']['baseValue'], 6),
    'manaGrowth': round(resource['{6216bf7b}']['baseValue'], 6),
    'damage': value('baseDamageModifiable'), 'damageGrowth': value('damagePerLevelModifiable'),
    'armor': value('baseArmorModifiable'), 'armorGrowth': value('armorPerLevelModifiable'),
    'magicResist': value('baseMR'), 'magicResistGrowth': value('mrPerLevel'),
    'attackSpeed': value('attackSpeedModifiable'), 'attackSpeedGrowth': value('attackSpeedPerLevelModifiable') / 100,
    'healthRegen': value('baseStaticHPRegenModifiable'), 'healthRegenGrowth': value('hpRegenPerLevelModifiable'),
    'manaRegen': round(resource['{c4ab3550}']['baseValue'], 6),
    'manaRegenGrowth': round(resource['{3a509002}']['baseValue'], 6),
    'growthFactors': [round(f, 6) for f in factors[:18]],
}
Path('src/content/ashe-progression.ts').write_text(
    '// Generated by tools/assets/export-ashe-progression.py; original floats retained in the reference pin.\n'
    + 'export const ASHE = ' + json.dumps(data, indent=2) + ' as const;\n')
print('Exported Ashe base stats, growth, regeneration, and 18 level factors')
