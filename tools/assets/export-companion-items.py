"""Pin original starter companion icons and regenerate their source-linked catalog."""
import argparse
import hashlib
import json
import subprocess
import urllib.request
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
sha = lambda raw: hashlib.sha256(raw).hexdigest()
parent_path = Path('docs/reference/jungle-companions-source.json')
parent = json.loads(parent_path.read_text())
raw = Path('.cache/jungle-quest/items.json').read_bytes()
assert sha(raw) == parent['itemSource']['sha256']
all_items = json.loads(raw)
items, icons = [], []
for identity, code, effect in [
    ('scorchclaw', '1101', 'Ember empowers attacks and abilities to burn and slow nearby enemies.'),
    ('gustwalker', '1102', 'Gain movement speed in brush and after large monster kills.'),
    ('mosstomper', '1103', 'Gain a refreshing shield after large monster kills or out of combat.'),
]:
    record = parent['itemSource']['records'][f'Items/{code}']
    dd = parent['dataDragon']['items'][code]
    assert record['price'] == dd['gold']['total'] == 450
    assert record['sellBackModifier'] == dd['gold']['sell'] == 0
    assert record['maxStack'] == 1 and record['mRequiredSpellName'] == 'SummonerSmite'
    assert 'Items/ItemGroups/DoransItems' in record['mItemGroups']
    assert dd['maps']['11'] and dd['gold']['purchasable']
    path = Path(f'public/assets/icons/{code}.png')
    url = f'https://ddragon.leagueoflegends.com/cdn/16.18.1/img/item/{code}.png'
    if not path.exists() and not args.check:
        path.write_bytes(urllib.request.urlopen(url, timeout=30).read())
    image = path.read_bytes()
    assert image.startswith(b'\x89PNG\r\n\x1a\n')
    icons.append(dict(path=str(path), url=url, sha256=sha(image)))
    items.append(dict(
        id=identity, name=dd['name'], price=record['price'], sell=0,
        description='Requires Smite. Feed your companion by killing large monsters. At full growth: ' + effect,
        icon=code, abilityPower=0, damage=0, armor=0, magicResist=0, hp=0, speed=0,
    ))
result = dict(
    parent=dict(path=str(parent_path), sha256=sha(parent_path.read_bytes())),
    itemMirror=dict(url=parent['itemSource']['url'], sha256=sha(raw)),
    groups={key: parent['itemSource']['records'][key]
            for key in ['Items/ItemGroups/GoldItems', 'Items/ItemGroups/DoransItems', 'Items/ItemGroups/BaseJungleItems']},
    blade=dict(path='Items/1055', record=all_items['Items/1055']), icons=icons,
    published=dict(url='https://www.leagueoflegends.com/en-us/news/dev/dev-season-2-gameplay-changes-preview/',
                   scope='Published position binding context. Selected Smite is the interim purchase binding; specific Smite-first/no-sale/consumed-group lifecycle rules are explicit adapters until native purchase callbacks and full roles are reconstructed.'),
    callbackBoundary='Parent scripts are metadata-only. Purchase/consumption phase and persistent group enforcement are explicit adapters; limited undo and the full role system remain unfinished.',
)
pin = Path('docs/reference/companion-items-source.json')
if pin.exists():
    assert json.loads(pin.read_text()) == result, 'Companion item source changed'
elif not args.check:
    pin.write_text(json.dumps(result, indent=2) + '\n')
else:
    raise AssertionError('Missing companion item source pin')
text = '// Generated by tools/assets/export-companion-items.py.\nexport const COMPANION_ITEMS = ' + json.dumps(items, indent=2) + ' as const;\n'
text = subprocess.run(['npx', 'prettier', '--stdin-filepath', 'src/content/companion-items.ts'],
                      input=text, text=True, capture_output=True, check=True).stdout
output = Path('src/content/companion-items.ts')
if args.check:
    assert output.read_text() == text, 'Companion catalog differs from source'
else:
    output.write_text(text)
    selling = Path('docs/reference/item-selling.json')
    prices = json.loads(selling.read_text())
    for code in ['1101', '1102', '1103']:
        dd = parent['dataDragon']['items'][code]
        prices['items'][code] = dict(name=dd['name'], gold=dd['gold'])
    selling.write_text(json.dumps(prices, indent=2) + '\n')
print('Verified three starter companion prices, ownership groups and original icons')
