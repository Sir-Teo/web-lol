"""Select authored Dust parameters; see ASHE-E.md for renderer integration policies."""
import json
from pathlib import Path
pin=json.loads(Path('docs/reference/hawkshot-effects.json').read_text())
e=next(e for e in pin['records']['Characters/Ashe/Skins/Skin0/Particles/Ashe_Base_E_mis']['data']['complexEmitterDefinitionData'] if e['emitterName']=='Dust')
assert e['isUniformScale']==1 and e['SpawnShape']['__type']=='VfxShapeBox'
assert e['numFrames']==4 and e['texDiv']==[2,2] and 'frameRate' not in e
assert 'bindWeight' not in e and 'primitive' not in e
assert e['worldAcceleration']['dynamics']['values']==[[0,0,0]]
assert e['Color']['dynamics']['times']==e['scale0']['dynamics']['times']==[0,1]
ranges=lambda v:[p.get('keyValues') for p in v['dynamics']['probabilityTables']]
data=dict(rate=e['rate']['constantValue'],lifetime=e['particleLifetime']['constantValue'],lifeRange=ranges(e['particleLifetime'])[0],
          linger=e['particleLinger'],box=e['SpawnShape']['Size'],velocity=e['birthVelocity']['constantValue'],drag=e['birthDrag']['constantValue'],
          orbitalRanges=ranges(e['birthOrbitalVelocity']),rotationRange=ranges(e['birthRotation0'])[0],
          birthScale=e['birthScale0']['constantValue'][0],scaleRange=ranges(e['birthScale0'])[0],
          scaleCurve=[v[0] for v in e['scale0']['dynamics']['values']],color=e['Color']['constantValue'],renderOrder=e['pass'])
Path('src/content/hawkshot-dust.ts').write_text('// Generated by tools/assets/export-hawkshot-dust.py.\nexport const HAWKSHOT_DUST = '+json.dumps(data,indent=2)+' as const;\n')
print('Exported pinned Dust motion, atlas and color parameters')
