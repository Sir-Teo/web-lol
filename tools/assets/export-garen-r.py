"""Export Garen R's named values without evaluating unresolved BotData formulas."""
import json
import hashlib
import struct
from pathlib import Path

pin = json.loads(Path('docs/reference/garen-character.json').read_text())
record = pin['records']['Characters/Garen/Spells/GarenRAbility/GarenR']
spell = record['mSpell']
client = json.loads(Path('docs/reference/garen-r-ddragon.json').read_text())
dd = client['spell']
assert client['version'] == '16.18.1' and dd['id'] == 'GarenR'
assert dd['maxrank'] == spell['mClientData']['mTooltipData']['mLists']['LevelUp']['levelCount'] == 3
values = {v['name']: v['values'] for v in spell['DataValues']}
assert all(len(v) == 7 for v in values.values())
assert spell['cooldownTime'][1:4] == dd['cooldown']
assert dd['cost'] == [0, 0, 0] and dd['range'] == [400, 400, 400]
assert len(set(values['RevealDuration'])) == 1
assert spell['mAnimationName'] == 'Spell4' and spell['useAnimatorFramerate']
assert spell['mCantCancelWhileWindingUp'] and spell['mCantCancelWhileChanneling']
assert 'Trait_Ultimate' in spell['mSpellTags']
assert '<trueDamage>' in dd['tooltip'] and 'missing Health' in dd['tooltip']
model = json.loads(Path('docs/reference/garen-model.json').read_text())
clips = model['animations']['data']['Characters/Garen/Animations/Skin0']['mClipDataMap']
assert clips['Spell4']['__type'] == 'SequencerClipData'
assert clips['Spell4']['mClipNameList'] == ['Spell4_Base', 'Idle1_Base']
path = model['atomicClips']['Spell4_Base']
entry = next(f for f in model['extraction']['files'] if f['path'] == path)
anm = Path('.cache/garen-current-sources', path).read_bytes()
assert len(anm) == entry['bytes'] and hashlib.sha256(anm).hexdigest() == entry['sha256']
# CompressedAnimationAsset v1 header, as already audited for Garen Q.
assert anm[:8] == b'r3d2canm' and struct.unpack_from('<I', anm, 8)[0] == 1
duration, fps = struct.unpack_from('<ff', anm, 36)
assert fps == 30 and duration > spell['castFrame'] / fps
out = dict(
    baseDamageByRank=values['BaseDamage'][1:4],
    missingHealthRatioByRank=values['ExecuteDamage'][1:4],
    cooldownSecondsByRank=spell['cooldownTime'][1:4],
    manaByRank=dd['cost'],
    castRange=dd['range'][0],
    revealSeconds=values['RevealDuration'][0],
    authoredCastSeconds=spell['spellCastTime'],
    authoredTotalSeconds=spell['spellTotalTime'],
    animationCastFrame=spell['castFrame'],
    useAnimatorFramerate=spell['useAnimatorFramerate'],
    cannotCancelWindup=spell['mCantCancelWhileWindingUp'],
    animationClip='spell4_base',
    animationFps=fps,
    animationSourceDuration=duration,
)
Path('src/content/garen-r.ts').write_text(
    '// Generated by tools/assets/export-garen-r.py; source roles and open integration work: docs/GAREN-R.md.\n'
    'export const GAREN_R = ' + json.dumps(out, indent=2) + ' as const;\n')
print('Exported three R ranks, cached client range and distinct authored timing fields.')
