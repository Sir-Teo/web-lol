"""Export Charm's authored tables; control execution is a local adapter policy."""
import argparse
import json
import runpy
from pathlib import Path

declarations = runpy.run_path(str(Path(__file__).with_name('export-ahri-declarations.py')))
ROOT, require = declarations['ROOT'], declarations['require']


def generate():
    pin, dd = declarations['load']()
    projected = declarations['project'](pin, dd)
    e = projected['spells'][2]
    root, public = e['declaration'], dd['spells'][2]
    named = {row['name']: row for row in e['dataValues']}
    require(len(named) == 4, 'E named-value closure changed')

    def constant(name):
        raw = named[name]['raw']
        require(all(value == raw[0] for value in raw), f'E constant became ranked: {name}')
        return raw[0]

    require(root['mSpellCalculations']['TotalDamage']['mFormulaParts'] == [
        {'mDataValue': 'BaseDamage', '__type': 'NamedDataValueCalculationPart'},
        {'mDataValue': 'APRatio', '__type': 'StatByNamedDataValueCalculationPart'},
    ], 'E damage calculation changed')
    require(public['image']['full'] == 'AhriE.png' and 'first enemy hit' in public['tooltip'],
            'E client identity/intent changed')
    missile = pin['records']['Characters/Ahri/Spells/AhriEAbility/AhriEMissile']['mSpell']
    spec = missile['mMissileSpec']
    movement = spec['movementComponent']
    require(movement['__type'] == 'FixedSpeedMovement' and movement['mTracksTarget'] is False
            and movement['mProjectTargetToCastRange'] is True, 'E missile movement changed')
    require([row['__type'] for row in spec['behaviors']]
            == ['CastOnHit', 'DestroyOnMovementComplete', 'DestroyOnHit'], 'E missile behavior changed')
    require(root['alwaysSnapFacing'] is True and root['mCantCancelWhileWindingUp'] is True,
            'E authored winding/facing declarations changed')
    values = dict(name=public['name'], description=public['description'], icon='AhriE',
                  castSeconds=root['mCastTime'], cooldownSecondsByRank=e['cooldownSecondsByRank'],
                  manaByRank=e['manaByRank'], damageByRank=named['BaseDamage']['rankValues'],
                  abilityPowerRatio=constant('APRatio'), charmSecondsByRank=named['CharmDuration']['rankValues'],
                  negativeSlowPercent=constant('SlowPercent'), alwaysSnapFacing=root['alwaysSnapFacing'],
                  displayRangeByRank=e['displayRangeByRank'], rawRootCastRange=root['castRange'],
                  genericRootMissileSpeed=root['missileSpeed'],
                  missile=dict(authoredWidth=spec['mMissileWidth'], speed=movement['mSpeed'],
                               rawCastRange=missile['castRange'], rawDisplayRange=missile['castRangeDisplayOverride']))
    return ('// Generated by tools/assets/export-ahri-e.py; see docs/AHRI.md.\n'
            '// Negative SlowPercent and root/child ranges remain separate declarations.\n'
            'export const AHRI_E = ' + json.dumps(values, indent=2, allow_nan=False) + ' as const;\n').encode()


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    declarations['publish'](generate(), ROOT / 'src/content/ahri-e.ts', args.check)
    print('Verified Charm root ranks/calculation, negative slow and first-hit directional missile declarations.')
