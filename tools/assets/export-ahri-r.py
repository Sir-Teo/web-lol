"""Export Spirit Rush source declarations; dash/recast execution remains a local policy."""
import argparse
import json
import runpy
from pathlib import Path

declarations = runpy.run_path(str(Path(__file__).with_name('export-ahri-declarations.py')))
ROOT, require = declarations['ROOT'], declarations['require']


def generate():
    pin, dd = declarations['load']()
    r = declarations['project'](pin, dd)['spells'][3]
    root, public = r['declaration'], dd['spells'][3]
    named = {row['name']: row for row in r['dataValues']}
    require(len(named) == 11, 'R named-value closure changed')

    def constant(name):
        raw = named[name]['raw']
        require(all(value == raw[0] for value in raw), f'R constant became ranked: {name}')
        return raw[0]

    require(root['mSpellCalculations']['RCalculatedDamage']['mFormulaParts'] == [
        {'mDataValue': 'RBaseDamage', '__type': 'NamedDataValueCalculationPart'},
        {'mDataValue': 'rAPCoefficient', '__type': 'StatByNamedDataValueCalculationPart'},
    ], 'R calculation changed')
    require(root['cantCastWhileRooted'] is True and root['mAnimationName'] == 'Spell4',
            'R movement restriction/body animation changed')
    require(all(key not in root for key in ['mCastTime', 'spellCastTime', 'mCanCastWhileDisabled', 'mCanCastWhileDead']),
            'R omitted cast/permission contract changed')
    require(public['image']['full'] == 'AhriR.png' and 'prioritizing champions' in public['tooltip']
            and 'up to 2 more times' in public['tooltip'] and "Consuming a champion's Essence" in public['tooltip'],
            'R client identity/intent changed')
    missile = pin['records']['Characters/Ahri/Spells/AhriRAbility/AhriRMissile']['mSpell']
    spec = missile['mMissileSpec']
    require(spec['movementComponent']['__type'] == 'FixedSpeedMovement'
            and [row['__type'] for row in spec['behaviors']] == ['CastOnMovementComplete', 'DestroyOnMovementComplete'],
            'R child movement/behavior changed')
    values = dict(name=public['name'], description=public['description'], icon='AhriR',
                  cooldownSecondsByRank=r['cooldownSecondsByRank'], manaByRank=r['manaByRank'],
                  damageByRank=named['RBaseDamage']['rankValues'], abilityPowerRatio=constant('RAPCoefficient'),
                  maxTargets=constant('RMaxTargetsPerCast'), maxCasts=constant('RMaxCasts'),
                  dashDistance=constant('RDashDistance'), baseDashSpeed=constant('RBaseDashSpeed'),
                  recastWindowSeconds=constant('RRecastWindow'), acquisitionRange=constant('RAcquisitionRange'),
                  dashCooldownSeconds=constant('RDashCooldown'), resetCasts=constant('RResetCasts'),
                  passiveDurationExtensionSeconds=constant('PDurationExtension'),
                  animation=root['mAnimationName'], cantCastWhileRooted=root['cantCastWhileRooted'],
                  displayRangeByRank=r['displayRangeByRank'], rawRootCastRange=root['castRange'],
                  genericRootMissileSpeed=root['missileSpeed'],
                  missile=dict(speed=spec['movementComponent']['mSpeed'], rawCastRange=missile['castRange']))
    return ('// Generated by tools/assets/export-ahri-r.py; see docs/AHRI.md.\n'
            '// Root named tables do not establish native dash/recast/Essence execution.\n'
            'export const AHRI_R = ' + json.dumps(values, indent=2, allow_nan=False) + ' as const;\n').encode()


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    declarations['publish'](generate(), ROOT / 'src/content/ahri-r.ts', args.check)
    print('Verified Spirit Rush named ranks, calculation, recast/dash declarations and child missile.')
