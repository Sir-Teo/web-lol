"""Export Garen stats from the retained 16.18 character records; no network needed."""
import json
import math
from pathlib import Path

pin = json.loads(Path('docs/reference/garen-character.json').read_text())
records = pin['records']
root = records['Characters/Garen/CharacterRecords/Root']
def value(key):
    return round(root[key]['baseValue'], 6)
resource = root['primaryAbilityResource']
fields = {
    'hp': 'baseHPModifiable', 'hpGrowth': 'hpPerLevelModifiable',
    'damage': 'baseDamageModifiable', 'damageGrowth': 'damagePerLevelModifiable',
    'armor': 'baseArmorModifiable', 'armorGrowth': 'armorPerLevelModifiable',
    'magicResist': 'baseMR', 'magicResistGrowth': 'mrPerLevel',
    'attackSpeed': 'attackSpeedModifiable', 'attackSpeedRatio': 'attackSpeedRatioModifiable',
    'healthRegen': 'baseStaticHPRegenModifiable', 'healthRegenGrowth': 'hpRegenPerLevelModifiable',
    'speed': 'baseMoveSpeedModifiable', 'range': 'attackRangeModifiable',
}
data = {key: value(field) for key, field in fields.items()}
for key, field in [('mana', '{726ee5cd}'), ('manaGrowth', '{6216bf7b}'),
                   ('manaRegen', '{c4ab3550}'), ('manaRegenGrowth', '{3a509002}')]:
    data[key] = round(resource.get(field, {'baseValue': 0})['baseValue'], 6)
data['attackSpeedGrowth'] = value('attackSpeedPerLevelModifiable') / 100
# Conventional 30% base windup plus the authored offset; native timing uncalibrated.
data['windupTicks'] = math.floor((0.3 + root['basicAttack']['mAttackDelayCastOffsetPercent']) * 60 / data['attackSpeed'] + 0.5)
data['selectionRadius'] = root['selectionRadius']
data['selectionHeight'] = root['selectionHeight']
data['attackDelayCastOffsetPercent'] = root['basicAttack']['mAttackDelayCastOffsetPercent']
data['attackDelayCastOffsetPercentAttackSpeedRatio'] = root['basicAttack']['mAttackDelayCastOffsetPercentAttackSpeedRatio']
data['pathfindingCollisionRadius'] = root['pathfindingCollisionRadius']
assert all(data[k] == 0 for k in ['mana', 'manaGrowth', 'manaRegen', 'manaRegenGrowth'])
# Resource growth fields are absent; explicit zero-resource policy retained.
# Melee projectile/attack dispatch is not inferred from an omitted missile field.
Path('src/content/garen-progression.ts').write_text(
    '// Generated by tools/assets/export-garen-progression.py; windup is a base adapter calculation; source scaling parameter retained, not yet integrated.\n'
    + 'export const GAREN = ' + json.dumps(data, indent=2) + ' as const;\n')
print('Exported Garen stats, selection dimensions and attack timing')
