"""Verify the pinned Ashe Q record and export its rank-independent active duration."""
import hashlib
import json
from pathlib import Path

pin = json.loads(Path('docs/reference/ashe-q.json').read_text())
raw = Path('.cache/ashe-16.18.json').read_bytes()
assert hashlib.sha256(raw).hexdigest() == pin['sha256']
record = json.loads(raw)[pin['record']]
assert record == pin['data']
values = next(value['values'] for value in record['mSpell']['DataValues']
              if value['name'] == 'BuffDuration')
assert len(set(values)) == 1 and values[0] > 0
Path('src/content/ashe-q.ts').write_text(
    '// Generated by tools/assets/export-ashe-q.py; see docs/ASHE-Q.md.\n'
    + 'export const ASHE_Q = ' + json.dumps({'durationSeconds': values[0]}, indent=2) + ' as const;\n')
print('Verified Ashe Q source and exported active duration')
