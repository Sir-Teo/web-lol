"""Verify the pinned Ashe Q record and export timing, stacks, and attack-speed values."""
import hashlib
import json
from pathlib import Path

pin = json.loads(Path('docs/reference/ashe-q.json').read_text())
raw = Path('.cache/ashe-16.18.json').read_bytes()
assert hashlib.sha256(raw).hexdigest() == pin['sha256']
record = json.loads(raw)[pin['record']]
assert record == pin['data']
tooltip_raw = Path('.cache/lol-strings-16.18.json').read_bytes()
tooltip = pin['stackingTooltip']
assert hashlib.sha256(tooltip_raw).hexdigest() == tooltip['sha256']
assert json.loads(tooltip_raw)['entries'][tooltip['key']] == tooltip['value']
data = {}
for name, field in [('BuffDuration', 'durationSeconds'), ('StackDuration', 'stackSeconds'),
                    ('StackFalloffDuration', 'falloffSeconds'), ('MaxStacks', 'maxStacks')]:
    values = next(value['values'] for value in record['mSpell']['DataValues'] if value['name'] == name)
    assert len(set(values)) == 1 and values[0] > 0
    data[field] = values[0]
bonus = next(value['values'] for value in record['mSpell']['DataValues'] if value['name'] == 'BonusAS')
data['bonusAttackSpeedByRank'] = [value / 100 for value in bonus[1:6]]
ratio = pin['attackSpeedRatio']
assert json.loads(raw)[ratio['record']][ratio['field']] == ratio['data']
data['attackSpeedRatio'] = round(ratio['data']['baseValue'], 6)
Path('src/content/ashe-q.ts').write_text(
    '// Generated by tools/assets/export-ashe-q.py; see docs/ASHE-Q.md.\n'
    + 'export const ASHE_Q = ' + json.dumps(data, indent=2) + ' as const;\n')
print('Verified Ashe Q source and tooltip; exported timing and stack values')
