"""Verify the pinned Heal record and export its currently supported self-cast rules."""
import hashlib
import json
from pathlib import Path

pin = json.loads(Path('docs/reference/summoner-heal.json').read_text())
raw = Path('.cache/shared-16.18.json').read_bytes()
assert hashlib.sha256(raw).hexdigest() == pin['sha256']
assert json.loads(raw)[pin['key']] == pin['record']
spell = pin['record']['mSpell']
part, = spell['mSpellCalculations']['TotalHeal']['mFormulaParts']
assert part['__type'] == 'ByCharLevelInterpolationCalculationPart'
values = {value['name']: value['values'][0] for value in spell['DataValues']}
data = {
    'minimumHeal': part['mStartValue'], 'maximumHeal': part['mEndValue'],
    'cooldownSeconds': spell['cooldownTime'][0],
    'canCastWhileDisabled': spell['canCastWhileDisabled'],
    'preservesRecall': spell['mDoesntBreakChannels'],
    'speedBonus': round(values['MoveSpeed'], 6),
    'speedDurationSeconds': values['MoveSpeedDuration'],
}
Path('src/content/summoner-heal.ts').write_text(
    '// Generated by tools/assets/export-summoner-heal.py; see docs/reference/summoner-heal.json.\n'
    + 'export const SUMMONER_HEAL = ' + json.dumps(data, indent=2) + ' as const;\n')
print('Verified Heal source and exported self-cast rules')
