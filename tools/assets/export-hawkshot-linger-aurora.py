"""Export the single lingering Aurora's complete authored playback parameters."""
from pathlib import Path
import hashlib,json
p=json.loads(Path('docs/reference/hawkshot-linger.json').read_text())
assert hashlib.sha256(Path('docs/reference/hawkshot-effects.json').read_bytes()).hexdigest()==p['definitionsSha256']
e=p['emitters'][0]
assert e['emitterName']=='Aurora' and e['isSingleParticle']==1
data=dict(life=e['particleLifetime']['dynamics']['values'][0],lifeRange=e['particleLifetime']['dynamics']['probabilityTables'][0]['keyValues'],
 radius=e['SpawnShape']['radius'],offset=e['EmitterPosition']['constantValue'],velocity=e['birthVelocity']['constantValue'],
 scale=e['birthScale0']['constantValue'],rotation=e['birthRotation0']['constantValue'],color=e['Color']['constantValue'],
 alphaTimes=e['Color']['dynamics']['times'],alpha=[v[3] for v in e['Color']['dynamics']['values']],
 erosion=e['alphaErosionDefinition']['erosionDriveCurve']['dynamics']['values'],featherOut=e['alphaErosionDefinition']['erosionFeatherOut'],
 scroll=e['textureMult']['birthUvScrollRateMult']['constantValue'])
Path('src/content/hawkshot-linger-aurora.ts').write_text('// Generated by tools/assets/export-hawkshot-linger-aurora.py.\nexport const HAWKSHOT_LINGER_AURORA = '+json.dumps(data,indent=2)+' as const;\n')
print('Exported lingering Aurora profile')
