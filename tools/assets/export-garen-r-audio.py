"""Ship unchanged R float masters and export cast/hit/kill container policies."""
from pathlib import Path
import hashlib
import json
import subprocess

sha = lambda b: hashlib.sha256(b).hexdigest()
graph_path = Path('docs/reference/garen-r-audio.json')
graph = json.loads(graph_path.read_text())
decoded_path = Path('docs/reference/garen-r-audio-decoded.json')
decoded = json.loads(decoded_path.read_text())
assert decoded['sourceGraphSha256'] == sha(graph_path.read_bytes())
nodes = {n['id']: n for n in graph['nodes']}
def parameter(identity, ending):
    found = [p for p in nodes[identity]['parameters'] if p[0].endswith('/' + ending)]
    assert len(found) == 1, (identity, ending)
    return found[0][2]
def properties(identity):
    fields = nodes[identity]['parameters']; result = {}
    for f in fields:
        if f[0].endswith('/pID'):
            key = f[3].split('[')[-1].removesuffix(']')
            value = next(p[2] for p in fields if p[0] == f[0][:-3] + 'pValue')
            assert key not in result, (identity, key)
            result[key] = float(value)
    return result
events = {e['name']: e for e in graph['events']}
profile = {}
for role, name, target_id, gain in [('cast', 'OnCast', 337811635, -11), ('hit', 'OnHit', 251427808, -12), ('kill', 'buffactivate', 818893250, -13.5)]:
    event = events['Play_sfx_Garen_GarenR_' + name]
    assert len(event['actions']) == 1
    action = event['actions'][0]; assert action['target'] == target_id
    assert not properties(action['id'])
    assert properties(target_id) == {'MakeUpGain': gain}
    assert int(parameter(target_id, 'DirectParentID')) == 1017337109
    policy = {k: int(parameter(target_id, k)) for k in ['eMode', 'eRandomMode', 'wAvoidRepeatCount',
        'bResetPlayListAtEachPlay', 'bIsGlobal', 'bIsContinuous', '_bIsUsingWeight',
        'u16MaxNumInstance', 'bKillNewest', 'sLoopCount', 'sLoopModMin', 'sLoopModMax', 'eTransitionMode']}
    assert policy['eMode'] == 0 and policy['eRandomMode'] == 1 and policy['wAvoidRepeatCount'] == 0
    assert policy['bIsContinuous'] == 0 and policy['sLoopCount'] == 1
    assert policy['bKillNewest'] == 0 and policy['_bIsUsingWeight'] == 0
    variants = []
    for i in range(int(parameter(target_id, 'ulPlayListItem'))):
        sound_id = int(parameter(target_id, f'AkPlaylistItem:{i}/ulPlayID'))
        media_id = int(parameter(sound_id, 'sourceID'))
        assert not properties(sound_id)
        assert int(parameter(target_id, f'AkPlaylistItem:{i}/weight')) == 50000
        m = next(m for m in decoded['media'] if m['id'] == media_id)
        assert m['decoderMetadata']['loopingInfo'] is None and m['sampleRate'] == 44100 and m['channels'] == (2 if role == 'kill' else 1)
        raw = (Path('.cache/garen-r-audio-decoded') / f'{media_id}.wav').read_bytes()
        assert sha(raw) == m['wavSha256']
        output = Path(f'public/assets/audio/garen-r-{media_id}.wav'); output.write_bytes(raw)
        variants.append(dict(id=media_id, soundId=sound_id, url=str(output).removeprefix('public/'),
            sha256=m['wavSha256'], pcmSha256=m['pcmSha256'], frames=m['frames'], sampleRate=m['sampleRate'],
            channels=m['channels'], durationSeconds=m['durationSeconds'], peak=m['peak']))
    assert {v['id'] for v in variants} == set(action['affectedMediaIds'])
    profile[role] = dict(eventId=event['id'], actionId=action['id'], targetId=target_id, gainDb=gain,
        policy=policy, variants=variants, maxDurationSeconds=max(v['durationSeconds'] for v in variants))
assert properties(1017337109) == {}
assert int(parameter(1017337109, 'DirectParentID')) == 428652767
assert properties(428652767) == {'Priority': 60, 'AttenuationID': 339248780}
assert int(parameter(428652767, 'OverrideBusId')) == 1259461568
assert int(parameter(339248780, 'eScaling')) == 2
assert int(parameter(339248780, 'curveToUse[0]')) == 0
points = [dict(distance=float(parameter(339248780, f'AkRTPCGraphPoint:{i}/From')),
    storedValue=float(parameter(339248780, f'AkRTPCGraphPoint:{i}/To')),
    interpolation=int(parameter(339248780, f'AkRTPCGraphPoint:{i}/Interp'))) for i in range(6)]
profile['attenuation'] = dict(id=339248780, scaling=2, points=points, unresolvedOutputBusId=1259461568)
link_path = Path('docs/reference/garen-r-kill-audio-link.json')
link = json.loads(link_path.read_text())
assert link['definition']['soundOnCreateDefault'] == events['Play_sfx_Garen_GarenR_buffactivate']['name']
profile['killParticleLinkSha256'] = sha(link_path.read_bytes())
assert not any(e['name'].startswith('Stop_') for e in graph['events'])
output = Path('src/content/garen-r-audio.ts')
output.write_text('// Generated by tools/assets/export-garen-r-audio.py.\n'
    '// Source policy; native dispatch, random state, voice priority and bus mix remain unverified.\n'
    + 'export const GAREN_R_AUDIO = ' + json.dumps(profile, indent=2) + ' as const;\n')
subprocess.run(['npx', 'prettier', '--write', str(output)], check=True, stdout=subprocess.DEVNULL)
timing = Path('src/content/garen-r-audio-timing.ts')
import math
tail = max(180, math.ceil(max(profile[k]['maxDurationSeconds'] for k in ['cast','hit','kill']) * 60))
timing.write_text('// Generated by tools/assets/export-garen-r-audio.py.\n'
    '// Shared R history must retain the longest unnormalized sound tail.\n'
    + f'export const GAREN_R_AUDIO_TAIL_TICKS = {tail};\n')
print(json.dumps(dict(roles={k: dict(variants=len(profile[k]['variants']), gainDb=profile[k]['gainDb'], seconds=profile[k]['maxDurationSeconds']) for k in ['cast', 'hit', 'kill']},
    shippedBytes=sum((Path('public') / v['url']).stat().st_size for k in ['cast', 'hit', 'kill'] for v in profile[k]['variants']))))
