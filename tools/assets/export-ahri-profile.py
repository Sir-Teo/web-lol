"""Export the development Ahri NPC profile from checked source declarations.

The local policy explicitly selects BIN AD growth despite the unresolved public
client disagreement. No native attack timing or critical policy is recovered.
"""
import argparse
import json
import runpy
from pathlib import Path

declarations = runpy.run_path(str(Path(__file__).with_name('export-ahri-declarations.py')))
ROOT, require = declarations['ROOT'], declarations['require']


def generate():
    pin, dd = declarations['load']()
    projection = declarations['project'](pin, dd)
    values = {row['name']: row['sourceValue'] for row in projection['stats']}
    values['attackSpeedGrowth'] /= 100
    root = projection['character']['declaration']
    for field in ['attackSpeedRatio', 'selectionRadius', 'selectionHeight',
                  'pathfindingCollisionRadius', 'attackDelayCastOffsetPercent']:
        values[field] = (root['attackSpeedRatioModifiable']['baseValue'] if field == 'attackSpeedRatio'
                         else root['basicAttack']['mAttackDelayCastOffsetPercent']
                         if field == 'attackDelayCastOffsetPercent' else root[field])
    basic = pin['records']['Characters/Ahri/Spells/AhriBasicAttack']['mSpell']
    movement = basic['mMissileSpec']['movementComponent']
    require(movement['__type'] == 'FixedSpeedMovement' and movement['mSpeed'] == 1750,
            'Basic attack missile declaration changed')
    values['missileSpeed'] = movement['mSpeed']
    require(values['damageGrowth'] == 3 and dd['stats']['attackdamageperlevel'] == 0,
            'Explicit local AD-growth choice changed')
    return ('// Generated by tools/assets/export-ahri-profile.py; see docs/AHRI.md.\n'
            '// Development policy uses BIN growth 3; Data Dragon 0 remains unresolved.\n'
            'export const AHRI = ' + json.dumps(values, indent=2, allow_nan=False) + ' as const;\n').encode()


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    declarations['publish'](generate(), ROOT / 'src/content/ahri-progression.ts', args.check)
    print('Verified Ahri development profile; explicit BIN AD growth, no spell kit generated.')
