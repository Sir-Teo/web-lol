"""Pin standard Smite records, original script metadata and source target tags."""
import json
from pathlib import Path
from xxhash import xxh64_intdigest
from riot_archive import RiotArchive, sha
from lua51 import read_chunk, named_functions, instruction

ROOT = Path('.cache/smite')
PIN = Path('docs/reference/summoner-smite-source.json')
old = json.loads(PIN.read_text()) if PIN.exists() else None
shared = ROOT / 'shared.json'
strings = ROOT / 'strings.json'
assert sha(shared.read_bytes()) == '8726e915a7c913c826bf3a722e548d002e8e41677073a585d40e8d179d0dd8bf'
assert sha(strings.read_bytes()) == 'bdee3e3636feb8e1cb5ac11e09e213c9115df2b04910c1f7eb6acc3e7d0d479d'
records = json.loads(shared.read_text())
entries = json.loads(strings.read_text())['entries']
keys = ['Shared/Spells/SummonerSmite', 'Shared/Spells/SummonerSmiteFirstCharge']
text_keys = ['spell_summonersmite_name', 'spell_summonersmite_tooltip',
             'spell_smite_shared_rules', 'spell_smite_cooldown_and_recharge']
parent_path = Path('docs/reference/jungle-character-source.json')
parent = json.loads(parent_path.read_text())
characters = dict(gromp='SRU_Gromp', blue='SRU_Blue', red='SRU_Red', wolf='SRU_Murkwolf',
                  **{'wolf-mini':'SRU_MurkwolfMini', 'raptor':'SRU_Razorbeak',
                     'raptor-mini':'SRU_RazorbeakMini', 'krug':'SRU_Krug',
                     'krug-medium':'SRU_KrugMini', 'krug-mini':'SRU_KrugMiniMini', 'scuttler':'Sru_Crab'})
tags = {}
for species, name in characters.items():
    path = f'data/characters/{name.lower()}/{name.lower()}.bin'
    key = f'Characters/{name}/CharacterRecords/Root'
    tags[species] = dict(path=path, key=key, unitTagsString=parent['records'][path][key]['unitTagsString'])
script_parent = json.loads(Path('docs/reference/jungle-script-source.json').read_text())['extraction']
paths = {f['wadPathHash']:f['path'] for f in script_parent['files']}
scripts = [f'data/spells/{n}.luabin64' for n in ['summonersmite','summonersmitefirstcharge','summonersmiteinitializer']]
paths.update({f'{xxh64_intdigest(p):016x}':p for p in scripts})
a = RiotArchive(paths, old['scripts'] if old else None, archive_name=script_parent['archive'])
a.extract(scripts, ROOT / 'scripts')
inventory = {}
for path in scripts:
    root = read_chunk((ROOT/'scripts'/path).read_bytes())
    inventory[path] = {name:dict(constants=f['constants'], codeSha256=f['codeSha256'],
        instructions=[instruction(f, pc) for pc in range(1,len(f['words'])+1)], children=len(f['children']))
        for name,f in named_functions(root).items()}
icon = Path('public/assets/icons/SummonerSmite.png')
result = dict(referenceVersion='16.18.8175716',
    shared=dict(url='https://raw.communitydragon.org/16.18/game/shared.cdtb.bin.json',sha256=sha(shared.read_bytes()),records={k:records[k] for k in keys}),
    strings=dict(url='https://raw.communitydragon.org/16.18/game/en_us/data/menu/en_us/lol.stringtable.json',sha256=sha(strings.read_bytes()),entries={k:entries[k] for k in text_keys}),
    icon=dict(path=str(icon),url='https://ddragon.leagueoflegends.com/cdn/16.18.1/img/spell/SummonerSmite.png',sha256=sha(icon.read_bytes())),
    characterSource=dict(path=str(parent_path),sha256=sha(parent_path.read_bytes()),tags=tags),
    scripts=a.provenance(),scriptInventory=inventory,
    published=dict(url='https://www.leagueoflegends.com/en-us/news/game-updates/patch-26-1-notes/',damage=[600,1000,1400],firstEvolutionKills=15,fullQuestStacks=35),
    limits=['Standard SummonerSmite is selected; legacy Duel and alternate-mode records are not active standard rules.',
            'Scripts retain metadata assignments and RETURN only; no active damage, startup or recharge callback is recovered.',
            'Initial ammo and first recharge anchor, target forgiveness, native range edges, cast latency and visual/audio dispatch need runtime comparison.',
            'Quest/pet evolution controls upgraded Smite; champion-level upgrades are not inferred. Role binding, pets and quest rewards remain unfinished.'])
if old:
    assert result == old, 'Smite source differs from pin'
else:
    PIN.write_text(json.dumps(result,indent=2)+'\n')
s = records[keys[0]]['mSpell']
values = {v['name']:v['values'][0] for v in s['DataValues']}
profile = dict(baseDamage=values['SmiteBaseDamage'], upgradedDamage=values['SmiteUpgradedDamage'],
    finalDamage=values['Smite2ndUpgradedDamage'], range=s['castRange'][0],
    useBoundingBoxes=s['castRangeUseBoundingBoxes'], maxCharges=s['mMaxAmmo'][0],
    rechargeSeconds=s['mAmmoRechargeTime'][0], cooldownSeconds=s['cooldownTime'][0],
    canCastWhileDisabled=s['canCastWhileDisabled'], preservesRecall=s['mDoesntBreakChannels'],
    monsterTags={k:v['unitTagsString'].split(' | ') for k,v in tags.items()})
output = '// Generated by tools/assets/extract-smite.py; startup policy is separate.\nexport const SUMMONER_SMITE = '+json.dumps(profile,indent=2)+' as const;\n'
Path('src/content/summoner-smite.ts').write_text(output)
print('Pinned standard Smite, three original metadata scripts, eleven Root tag sets and source icon; exported supported values')
