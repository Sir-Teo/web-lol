"""Export target lifetime appearance without discarding probability-table data silently."""
from pathlib import Path
import json
import runpy
import subprocess

verified = runpy.run_path('tools/assets/export-lux-binding-target-births.py')
audit = verified['audit']

def curve(value, default):
    dynamics=value.get('dynamics')
    if not dynamics:
        base=value.get('constantValue',default)
        return dict(times=[0,1],values=[base,base])
    for table in dynamics.get('probabilityTables',[]):
        assert not table.get('keyTimes') and not table.get('keyValues') and table.get('singleValue',1)==1
    assert len(dynamics['times'])==len(dynamics['values'])
    assert all(a<b for a,b in zip(dynamics['times'],dynamics['times'][1:]))
    return dict(times=dynamics['times'],values=dynamics['values'])

profiles=[]
for index,e in enumerate(audit['resolvedDefinition']['complexEmitterDefinitionData']):
    # No lifetime rotation curve occurs here; initial spin is sampled at birth.
    assert not e.get('rotation0')
    profiles.append(dict(index=index,name=e['emitterName'],uniform=bool(e.get('isUniformScale',False)),
        scale=curve(e.get('scale0',{}),[1,1,1]),color=curve(e.get('Color',{}),[1,1,1,1])))
out=Path('src/content/lux-binding-target-appearance.ts')
out.write_text('// Generated by tools/assets/export-lux-binding-target-appearance.py.\n'
    'export const LUX_BINDING_TARGET_APPEARANCE = '+json.dumps(profiles,indent=2)+' as const;\n')
subprocess.run(['npx','prettier','--write',str(out)],check=True,stdout=subprocess.DEVNULL)
print('Exported eleven target lifetime scale/color profiles.')
