"""Generate distinct source profiles for the two lingering snow emitters."""
from pathlib import Path
import hashlib,json
p=json.loads(Path('docs/reference/hawkshot-linger.json').read_text())
assert hashlib.sha256(Path('docs/reference/hawkshot-effects.json').read_bytes()).hexdigest()==p['definitionsSha256']
profiles=[]
for e in p['emitters']:
    if e['emitterName'] not in ['Snow01','Snow02']: continue
    assert e['texDiv']==[2,2] and e['numFrames']==4 and e['blendMode']==4
    assert all(t['keyValues']==[0,1] for t in e['SpawnShape']['emitOffset']['dynamics']['probabilityTables'])
    profiles.append(dict(name=e['emitterName'],rate=e['rate']['constantValue'],duration=e['lifetime'],
        life=e['particleLifetime']['constantValue'],lifeRange=e['particleLifetime']['dynamics']['probabilityTables'][0]['keyValues'],
        offset=e['EmitterPosition']['constantValue'],shape=e['SpawnShape']['emitOffset']['constantValue'],
        velocity=e['birthVelocity']['constantValue'],velocityRange=e['birthVelocity']['dynamics']['probabilityTables'][1]['keyValues'],
        drag=e.get('birthDrag',{}).get('constantValue',[0,0,0]),acceleration=e.get('worldAcceleration',{}).get('constantValue',[0,0,0]),
        orbit=e['birthOrbitalVelocity']['constantValue'],orbitYRange=e['birthOrbitalVelocity'].get('dynamics',{}).get('probabilityTables',[{}, {'keyValues':[1,1]}])[1]['keyValues'],
        scale=e['birthScale0']['constantValue'],scaleRange=e['birthScale0']['dynamics']['probabilityTables'][0]['keyValues'],
        growth=[v[0] for v in e['scale0']['dynamics']['values']],uniform=bool(e.get('isUniformScale',False)),directionOriented=bool(e.get('isDirectionOriented',False)),
        spin=e['birthRotationalVelocity0']['constantValue'][0],spinRange=e['birthRotationalVelocity0']['dynamics']['probabilityTables'][0]['keyValues'],color=e['Color']['constantValue'],renderOrder=e['pass']))
Path('src/content/hawkshot-snow.ts').write_text('// Generated by tools/assets/export-hawkshot-snow.py.\nexport const HAWKSHOT_SNOW = '+json.dumps(profiles,indent=2)+' as const;\n')
print('Exported both source snow profiles')
