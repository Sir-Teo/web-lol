"""Generate Sparkle playback parameters from the complete pinned linger record."""
from pathlib import Path
import hashlib, json
p = json.loads(Path('docs/reference/hawkshot-linger.json').read_text())
assert hashlib.sha256(Path('docs/reference/hawkshot-effects.json').read_bytes()).hexdigest() == p['definitionsSha256']
e = next(e for e in p['emitters'] if e['emitterName'] == 'Sparkle')
assert e['isUniformScale'] == 1 and e['blendMode'] == 4 and 'texDiv' not in e
assert all(t['keyValues'] == [0, 1] for t in e['SpawnShape']['emitOffset']['dynamics']['probabilityTables'])
assert e['SpawnShape']['emitRotationAngles'][0]['dynamics']['probabilityTables'][0]['keyValues'] == [0, 360]
assert e['birthVelocity']['constantValue'][0] == e['birthVelocity']['constantValue'][2] == 0
assert e['Color']['dynamics']['times'] == [0, 1] and e['Color']['dynamics']['values'][1][3] == 0
data = dict(rate=e['rate']['constantValue'], duration=e['lifetime'], life=e['particleLifetime']['constantValue'],
    lifeRange=e['particleLifetime']['dynamics']['probabilityTables'][0]['keyValues'],
    offset=e['EmitterPosition']['constantValue'], shape=e['SpawnShape']['emitOffset']['constantValue'],
    velocity=e['birthVelocity']['constantValue'], velocityRange=e['birthVelocity']['dynamics']['probabilityTables'][1]['keyValues'],
    scale=e['birthScale0']['constantValue'][0], scaleRange=e['birthScale0']['dynamics']['probabilityTables'][0]['keyValues'],
    growthTimes=e['scale0']['dynamics']['times'], growth=[v[0] for v in e['scale0']['dynamics']['values']],
    color=e['Color']['constantValue'], renderOrder=e['pass'])
Path('src/content/hawkshot-sparkle.ts').write_text('// Generated by tools/assets/export-hawkshot-sparkle.py.\nexport const HAWKSHOT_SPARKLE = '+json.dumps(data,indent=2)+' as const;\n')
print('Exported source Sparkle profile')
