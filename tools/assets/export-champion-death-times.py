"""Verify the standard Rift death-time record and export its base level table."""
import hashlib
import json
from pathlib import Path

pin = json.loads(Path('docs/reference/champion-death-times.json').read_text())
raw = Path('.cache/map11-definition.json').read_bytes()
assert hashlib.sha256(raw).hexdigest() == pin['sha256']
source = json.loads(raw)
assert source[pin['mode']]['mDeathTimes'] == pin['record']
assert source[pin['record']] == pin['data']
seconds = pin['data']['mTimeDeadPerLevel']
assert len(seconds) == 18 and all(value > 0 for value in seconds)
Path('src/content/champion-death-times.ts').write_text(
    '// Generated by tools/assets/export-champion-death-times.py. Base times only; see docs/CHAMPION-RECOVERY.md.\n'
    + 'export const CHAMPION_BASE_DEATH_SECONDS = ' + json.dumps(seconds, indent=2) + ' as const;\n')
print('Verified standard Rift death-time reference and exported 18 base times')
