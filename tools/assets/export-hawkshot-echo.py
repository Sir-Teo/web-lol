"""Verify the Owl3 emitter can reuse the shipped Owl2 geometry/rig/texture."""
import hashlib
import json
from pathlib import Path
pin_path = Path('docs/reference/hawkshot-effects.json')
pin = json.loads(pin_path.read_text())
record = 'Characters/Ashe/Skins/Skin0/Particles/Ashe_Base_E_mis'
emitters = pin['records'][record]['data']['complexEmitterDefinitionData']
e = next(e for e in emitters if e['emitterName'] == 'Owl3')
rim = next(e for e in emitters if e['emitterName'] == 'Owl2')
for key in ['primitive', 'texture', 'birthScale0', 'birthRotation0', 'isUniformScale', 'birthColor', 'blendMode', 'disableBackfaceCull']:
    assert e[key] == rim[key], key
assert e['bindWeight']['constantValue'] == 1
assert e['Color']['dynamics']['times'] == [0, 1]
assert e['Color']['dynamics']['values'][1][3] == 0
assert e['birthVelocity']['constantValue'] == [0, -300, 0]
data = dict(rate=e['rate']['constantValue'], lifetime=e['particleLifetime']['constantValue'],
            velocity=e['birthVelocity']['constantValue'], alpha=e['Color']['dynamics']['values'][0][3],
            fresnel=e['reflectionDefinition']['fresnel'], fresnelColor=e['reflectionDefinition']['fresnelColor'],
            renderOrder=e['pass'])
Path('src/content/hawkshot-echo.ts').write_text('// Generated by tools/assets/export-hawkshot-echo.py.\nexport const HAWKSHOT_ECHO = '+json.dumps(data,indent=2)+' as const;\n')
Path('docs/reference/hawkshot-echo.json').write_text(json.dumps(dict(definitionsSha256=hashlib.sha256(pin_path.read_bytes()).hexdigest(),record=record,emitter=e,reusesEmitter='Owl2'),indent=2)+'\n')
print('Verified Owl3 source and exact reusable Owl2 asset fields')
