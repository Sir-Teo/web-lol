"""Export the persistent source loop and authored stop fade without baking gain."""
from pathlib import Path
import hashlib,json,subprocess
p=Path('docs/reference/hawkshot-audio.json');graph=json.loads(p.read_text())
decoded=json.loads(Path('docs/reference/hawkshot-audio-decoded.json').read_text())
assert decoded['sourceGraphSha256']==hashlib.sha256(p.read_bytes()).hexdigest()
nodes={n['id']:n for n in graph['nodes']}
def prop(node,label):
 fields=nodes[node]['parameters']
 pid=next(p for p in fields if p[0].endswith('/pID') and f'[{label}]' in (p[3] or ''))
 return float(next(p[2] for p in fields if p[0]==pid[0][:-3]+'pValue'))
play=next(e for e in graph['events'] if e['name']=='Play_sfx_Ashe_AsheSpiritOfTheHawk_buffactivate')
stop=next(e for e in graph['events'] if e['name']=='Stop_sfx_Ashe_AsheSpiritOfTheHawk_buffactivate')
assert play['mediaIds']==[649034525] and play['actions']==[658242044] and stop['actions']==[852892569]
for action in (658242044,852892569):
 assert any(p[0].endswith('/idExt') and p[2]=='604153567' for p in nodes[action]['parameters'])
assert prop(604153567,'Loop')==0
assert any(p[0].endswith('/eFadeCurve') and '[Exp1]' in (p[3] or '') for p in nodes[852892569]['parameters'])
media=next(m for m in decoded['media'] if m['id']==649034525)
assert media['decoderMetadata']['loopingInfo'] is None
raw=Path('.cache/hawkshot-audio-decoded/649034525.wav').read_bytes()
assert hashlib.sha256(raw).hexdigest()==media['wavSha256']
target=Path('public/assets/audio/hawkshot-linger.wav');target.parent.mkdir(parents=True,exist_ok=True);target.write_bytes(raw)
profile=dict(eventId=play['id'],stopEventId=stop['id'],mediaId=media['id'],gainDb=prop(604153567,'MakeUpGain'),
             fadeSeconds=prop(852892569,'TransitionTime')/1000,fadeCurve=6,loop=True,
             url='/assets/audio/hawkshot-linger.wav',sha256=media['wavSha256'])
Path('src/content/hawkshot-linger-audio.ts').write_text('// Generated by tools/assets/export-hawkshot-linger-audio.py.\nexport const HAWKSHOT_LINGER_AUDIO = '+json.dumps(profile,indent=2)+' as const;\n')
subprocess.run(['npx','prettier','--write','src/content/hawkshot-linger-audio.ts'],check=True,stdout=subprocess.DEVNULL)
print(json.dumps(profile))
