"""Project frozen standard-mode Wuju Style values without inventing omitted fields.

The source omits mana and animation; public mana zero remains separate. Native
activation/contact/proc dispatch is not recovered. Existing output is immutable.
"""
import argparse
import json
import runpy
from pathlib import Path

source = runpy.run_path(str(Path(__file__).with_name('export-masteryi-declarations.py')))
ROOT, require = source['ROOT'], source['require']
SPELL = 'Characters/MasterYi/Spells/WujuStyleAbility/WujuStyle'


def generate():
    pin, dd = source['load']()
    records = pin['records']
    spell = records[SPELL]['mSpell']
    require(records[source['ROOT_RECORD']]['spells'][2] == SPELL,
            'E root binding changed')
    values = {row['name']: row['values'] for row in spell['DataValues']}
    require(values == {
        'BaseDamage': [15.0, 20.0, 25.0, 30.0, 35.0, 40.0, 45.0],
        'ADRatio': [0.3499999940395355]*7,
        'Duration': [5.0]*7, 'LegacySwordVFXDuration': [3.0]*7,
    }, 'Standard-mode named values changed')
    require(spell['mSpellCalculations']['TotalDamage'] == {
        'mSimpleTooltipCalculationDisplay': 6,
        'mFormulaParts': [
            {'mDataValue': 'BaseDamage', '__type': 'NamedDataValueCalculationPart'},
            {'mStat': 2, 'mStatFormula': 2, 'mDataValue': 'ADRatio',
             '__type': 'StatByNamedDataValueCalculationPart'},
        ], '__type': 'GameCalculation',
    }, 'Damage formula changed')
    public = dd['spells'][2]
    require(public['id'] == 'WujuStyle' and public['cost'] == [0]*5
            and public['cooldown'] == [14]*5 and spell['cooldownTime'] == [14.0]*7,
            'Public identity/resources or source cooldown changed')
    require('mana' not in spell and 'mAnimationName' not in spell,
            'Omitted resource/animation fields changed')
    require(spell['mCantCancelWhileWindingUp'] is True,
            'Root windup declaration changed')
    require(records['Characters/MasterYi/Spells/WujuStyleAbility']['mChildSpells'] == [
        SPELL, 'Characters/MasterYi/Spells/WujuStyleAbility/WujuStyleSuperCharged'
    ], 'Active buff binding changed')
    data = dict(name=public['name'], description=public['description'], icon=public['id'],
                baseDamageByRank=values['BaseDamage'][1:6],
                bonusAttackDamageRatio=values['ADRatio'][0], rawStatId=2, rawStatFormula=2,
                durationSeconds=values['Duration'][0],
                legacySwordVFXSeconds=values['LegacySwordVFXDuration'][0],
                cooldownSecondsByRank=spell['cooldownTime'][1:6],
                sourceMana=None, publicManaByRank=public['cost'],
                sourceAnimation=None, authoredCastSeconds=spell['spellCastTime'],
                authoredCannotCancelWindup=True, declaration=SPELL)
    return ('// Generated by tools/assets/export-masteryi-e.py.\n'
            '// Omitted BIN mana/animation remain null; native dispatch is unresolved.\n'
            'export const MASTER_YI_E = ' + json.dumps(data, indent=2) + ' as const;\n').encode()


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source['publish'](generate(), ROOT / 'src/content/masteryi-e.ts', args.check)
    print('Verified standard Wuju Style ranks/formula, duration, cooldown, buff binding and explicit source omissions.')
