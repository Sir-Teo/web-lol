"""Verify ordinary attack mesh identity and authored scale before sharing Q geometry."""
from pathlib import Path
import hashlib
import json

pin = json.loads(Path('docs/reference/ashe-basic-arrow.json').read_text())
raw = Path(pin['definitionCache']).read_bytes()
assert hashlib.sha256(raw).hexdigest() == pin['definitionSha256']
data = json.loads(raw)[pin['record']]
emitter = next(e for e in data['complexEmitterDefinitionData'] if e['emitterName'] == 'icearrow1')
assert emitter == pin['emitter']
resolver = Path(pin['resolverCache']).read_bytes()
assert hashlib.sha256(resolver).hexdigest() == pin['resolverSha256']
resources = json.loads(resolver)['Characters/Ashe/Skins/Skin0/Resources']['resourceMap']
assert resources[pin['resourceKey']] == pin['record']
q = json.loads(Path('docs/reference/ashe-q-arrow.json').read_text())
assert q['definitionSha256'] == pin['definitionSha256']
q_emitter = next(e for e in q['data']['complexEmitterDefinitionData'] if e['emitterName'] == 'icearrow')
for field in ['primitive', 'texture', 'blendMode', 'birthRotation0', 'particleIsLocalOrientation']:
    assert emitter[field] == q_emitter[field], field
assert not emitter.get('disabled') and emitter['blendMode'] == 3
scale = emitter['birthScale0']['constantValue']
assert len(scale) == 3 and all(value > 0 for value in scale)
Path('src/content/ashe-basic-arrow.ts').write_text('// Generated by tools/assets/export-ashe-basic-arrow.py.\nexport const ASHE_BASIC_ARROW_SCALE = ' + json.dumps(scale) + ' as const;\n')
print('Verified ordinary/Q shared source mesh and texture; exported ordinary scale')
