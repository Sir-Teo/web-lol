"""Pin endpoint DarknessFollow and verify reuse of decoded smoke textures."""
from pathlib import Path
import hashlib, json

source = Path('docs/reference/hawkshot-effects.json')
p = json.loads(source.read_text())
record = 'Characters/Ashe/Skins/Skin0/Particles/Ashe_Base_E_tar_explode'
e = next(e for e in p['records'][record]['data']['complexEmitterDefinitionData'] if e['emitterName'] == 'DarknessFollow')
assert e['isSingleParticle'] == 1 and e['blendMode'] == 4 and e['isUniformScale'] == 1
assert e['alphaErosionDefinition']['erosionMapChannelMixer']['constantValue'] == [0, 0, 1, 0]
sprites = json.loads(Path('docs/reference/hawkshot-sprites.json').read_text())
textures = []
wind = json.loads(Path('public/assets/models/hawkshot-wind.json').read_text())
w = next(t for t in wind['textures'] if t['name'] == 'erosion')
wind_texture = dict(path='public'+w['output'], sha256=w['pngSha256'], source=next(s for s in wind['sources'] if s['path'] == w['source']))
for name in [e['texture'], e['alphaErosionDefinition']['erosionMapName']]:
    t = next(t for t in [*sprites['textures'], wind_texture] if t['source']['path'] == name.lower())
    assert hashlib.sha256(Path(t['path']).read_bytes()).hexdigest() == t['sha256']
    textures.append(t)
data = dict(delay=e['timeBeforeFirstEmission'], life=e['particleLifetime']['constantValue'],
    lifeProbability=e['particleLifetime']['dynamics']['probabilityTables'][0],
    velocity=e['birthVelocity']['constantValue'], velocityRanges=[e['birthVelocity']['dynamics']['probabilityTables'][i]['keyValues'] for i in [0, 2]],
    offset=e['EmitterPosition']['constantValue'], spawnX=e['SpawnShape']['emitOffset']['constantValue'][0],
    spawnRange=e['SpawnShape']['emitOffset']['dynamics']['probabilityTables'][0]['keyValues'],
    color=e['Color']['constantValue'], alphaRange=e['birthColor']['dynamics']['probabilityTables'][3]['keyValues'],
    scale=e['birthScale0']['constantValue'][0], scaleRange=e['birthScale0']['dynamics']['probabilityTables'][0]['keyValues'],
    rotationRange=e['birthRotation0']['dynamics']['probabilityTables'][0]['keyValues'],
    erosion=e['alphaErosionDefinition']['erosionDriveCurve']['dynamics']['values'], frames=e['numFrames'])
Path('src/content/hawkshot-darkness.ts').write_text('// Generated by tools/assets/export-hawkshot-darkness.py.\nexport const HAWKSHOT_DARKNESS = '+json.dumps(data, indent=2)+' as const;\n')
Path('docs/reference/hawkshot-darkness.json').write_text(json.dumps(dict(definitionsSha256=hashlib.sha256(source.read_bytes()).hexdigest(), record=record, emitter=e, textures=textures, profile=data), indent=2)+'\n')
print('Verified DarknessFollow and both reused textures')
