"""Export Fox-Fire declarations without inventing native dispatch/targeting."""
import argparse
import json
import runpy
from pathlib import Path

declarations = runpy.run_path(str(Path(__file__).with_name('export-ahri-declarations.py')))
ROOT, require = declarations['ROOT'], declarations['require']


def generate():
    pin, dd = declarations['load']()
    projected = declarations['project'](pin, dd)
    w = projected['spells'][1]
    root, public = w['declaration'], dd['spells'][1]
    named = {row['name']: row for row in w['dataValues']}
    require(len(named) == 13, 'Named W value count changed')

    def constant(name):
        raw = named[name]['raw']
        require(all(value == raw[0] for value in raw), f'W constant became ranked: {name}')
        return raw[0]

    calculations = root['mSpellCalculations']
    require(calculations['SingleFireDamage']['mFormulaParts'] == [
        {'mDataValue': 'BaseDamage', '__type': 'NamedDataValueCalculationPart'},
        {'mDataValue': 'APRatio', '__type': 'StatByNamedDataValueCalculationPart'},
    ], 'W single-fire calculation changed')
    require(calculations['MultiFireDamage']['mModifiedGameCalculation'] == 'SingleFireDamage'
            and calculations['MultiFireDamage']['mMultiplier'] == {
                'mDataValue': 'RepeatDamageMod', '__type': 'NamedDataValueCalculationPart'},
            'W repeated-fire calculation changed')
    require(public['image']['full'] == 'AhriW.png'
            and 'Ahri releases 3 fox-fires' in public['tooltip'], 'Client W identity/count changed')
    records = pin['records']
    orbit = records['Characters/Ahri/Spells/AhriWAbility/AhriWMissile']['mSpell']
    damage = records['Characters/Ahri/Spells/AhriWAbility/AhriWDamageMissile']['mSpell']
    movement = orbit['mMissileSpec']['movementComponent']
    require(movement['__type'] == 'CircleMovement', 'W orbit movement type changed')
    splines = damage['mMissileSpec']['movementComponent']['MovementEntries']
    speeds = [row['MovementSpec']['mSpeed'] for row in splines]
    require(len(speeds) == 5 and len(set(speeds)) == 1, 'W damage spline speeds differ')
    require('DataValuesModeOverride' not in root, 'W mode override appeared')
    values = dict(name=public['name'], description=public['description'], icon='AhriW',
                  clientFireCount=3, authoredCastSeconds=root['mCastTime'],
                  cooldownSecondsByRank=w['cooldownSecondsByRank'], manaByRank=w['manaByRank'],
                  damageByRank=named['BaseDamage']['rankValues'],
                  abilityPowerRatio=constant('APRatio'), repeatDamageMultiplier=constant('RepeatDamageMod'),
                  movementSpeedFraction=constant('MovementSpeed'),
                  movementSpeedSeconds=constant('MovementSpeedDuration'),
                  minionDamageMultiplier=constant('MinionBonusDamageMultiplier'),
                  minionHealthThreshold=constant('MinionBonusDamageThreshold'),
                  acquisitionRange=constant('AcquisitionRange'), bonusAcquisitionRange=constant('BonusAcquisitionRange'),
                  initialDelaySeconds=constant('InitialDelay'), secondaryDelaySeconds=constant('SecondaryDelay'),
                  namedFlameDurationSeconds=constant('FlameDuration'), orbitRadius=constant('OrbitRadius'),
                  displayRangeByRank=w['displayRangeByRank'], rawCastRange=root['castRange'],
                  genericRootMissileSpeed=root['missileSpeed'], damageSplineSpeed=speeds[0],
                  orbit=dict(linearVelocity=movement['mLinearVelocity'], angularVelocity=movement['mAngularVelocity'],
                             lifetimeSeconds=movement['mLifetime']))
    return ('// Generated by tools/assets/export-ahri-w.py; see docs/AHRI.md.\n'
            '// Client fire count and named values do not establish native ownership or dispatch.\n'
            'export const AHRI_W = ' + json.dumps(values, indent=2, allow_nan=False) + ' as const;\n').encode()


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    declarations['publish'](generate(), ROOT / 'src/content/ahri-w.ts', args.check)
    print('Verified Fox-Fire client count, 13 named values, formulas, rank tables and distinct movement lifetimes.')
