"""Export the source arrival recording and mapped sound gain without normalizing."""
from pathlib import Path
import hashlib,json,subprocess

graph_path=Path('docs/reference/hawkshot-audio.json')
graph=json.loads(graph_path.read_text())
decoded=json.loads(Path('docs/reference/hawkshot-audio-decoded.json').read_text())
assert decoded['sourceGraphSha256']==hashlib.sha256(graph_path.read_bytes()).hexdigest()
event=next(e for e in graph['events'] if e['name']=='Play_sfx_Ashe_AsheSpiritOfTheHawk_hit')
assert event['actions']==[840123278] and event['mediaIds']==[381540917]
nodes={n['id']:n for n in graph['nodes']}
action=nodes[event['actions'][0]]['parameters']
assert any(p[0].endswith('/idExt') and p[2]=='108015836' for p in action)
assert not any('[DelayTime]' in (p[3] or '') for p in action)
fields=nodes[108015836]['parameters']
pid=next(p for p in fields if p[0].endswith('/pID') and '[MakeUpGain]' in (p[3] or ''))
gain=float(next(p[2] for p in fields if p[0]==pid[0][:-3]+'pValue'))
media=next(m for m in decoded['media'] if m['id']==381540917)
raw=Path('.cache/hawkshot-audio-decoded/381540917.wav').read_bytes()
assert hashlib.sha256(raw).hexdigest()==media['wavSha256']
target=Path('public/assets/audio/hawkshot-arrival.wav');target.parent.mkdir(parents=True,exist_ok=True);target.write_bytes(raw)
profile=dict(eventId=event['id'],mediaId=media['id'],gainDb=gain,delaySeconds=0,
             url='/assets/audio/hawkshot-arrival.wav',sha256=media['wavSha256'])
Path('src/content/hawkshot-arrival-audio.ts').write_text('// Generated by tools/assets/export-hawkshot-arrival-audio.py.\nexport const HAWKSHOT_ARRIVAL_AUDIO = '+json.dumps(profile,indent=2)+' as const;\n')
subprocess.run(['npx','prettier','--write','src/content/hawkshot-arrival-audio.ts'],check=True,stdout=subprocess.DEVNULL)
print(json.dumps(profile))
