"""Export Q's authored values; executable policies live in ahri-q-policy.ts."""
import argparse
import json
import runpy
from pathlib import Path

declarations = runpy.run_path(str(Path(__file__).with_name('export-ahri-declarations.py')))
ROOT, require = declarations['ROOT'], declarations['require']


def generate():
    pin, dd = declarations['load']()
    projected = declarations['project'](pin, dd)
    q = projected['spells'][0]
    root = q['declaration']
    parts = root['mSpellCalculations']['TotalDamage']['mFormulaParts']
    require(parts[0] == {'mDataValue': 'BaseDamage', '__type': 'NamedDataValueCalculationPart'}
            and parts[1] == {'mCoefficient': 0.5, '__type': 'StatByCoefficientCalculationPart'},
            'Root damage calculation changed')
    damage = next(value['rankValues'] for value in q['dataValues'] if value['name'] == 'BaseDamage')
    records = pin['records']

    def leg(name):
        spell = records[f'Characters/Ahri/Spells/AhriQAbility/{name}']['mSpell']
        spec = spell['mMissileSpec']
        movement = spec['movementComponent']
        require(movement['__type'] == 'AcceleratingMovement', 'Missile movement type changed')
        require([row['__type'] for row in spec['behaviors']]
                == ['CastOnHit', 'DestroyOnMovementComplete'], 'Missile behavior declarations changed')
        return dict(authoredWidth=spec['mMissileWidth'], rawCastRange=spell['castRange'],
                    initialSpeed=movement['mInitialSpeed'], minimumSpeed=movement['mMinSpeed'],
                    maximumSpeed=movement['mMaxSpeed'], acceleration=movement['mAcceleration'])

    public = dd['spells'][0]
    require(public['image']['full'] == 'AhriQ.png', 'Q icon identity changed')
    values = dict(name=public['name'], description=public['description'], icon='AhriQ',
                  castSeconds=root['mCastTime'], cooldownSecondsByRank=q['cooldownSecondsByRank'],
                  manaByRank=q['manaByRank'], namedDamageByRank=damage,
                  namedStatCoefficient=parts[1]['mCoefficient'],
                  displayRangeByRank=q['displayRangeByRank'], rawRootCastRange=root['castRange'],
                  genericRootMissileSpeed=root['missileSpeed'],
                  outward=leg('AhriQMissile'), returning=leg('AhriQReturnMissile'))
    return ('// Generated by tools/assets/export-ahri-q.py; see docs/AHRI.md.\n'
            '// Authored declarations only; damage caller, stat identity and integration remain unproven.\n'
            'export const AHRI_Q = ' + json.dumps(values, indent=2, allow_nan=False) + ' as const;\n').encode()


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    declarations['publish'](generate(), ROOT / 'src/content/ahri-q.ts', args.check)
    print('Verified Ahri Q root values and both independent accelerating missile declarations.')
