"""Select authored smoke values; omitted erosion defaults follow the documented WindTunnel policy."""
from pathlib import Path
import json
p=json.loads(Path('docs/reference/hawkshot-effects.json').read_text())
e=next(e for e in p['records']['Characters/Ashe/Skins/Skin0/Particles/Ashe_Base_E_mis']['data']['complexEmitterDefinitionData'] if e['emitterName']=='Smoke_Trail')
assert e['texDiv']==[2,2] and e['numFrames']==4 and 'frameRate' not in e
assert 'birthVelocity' not in e and 'bindWeight' not in e and 'isUniformScale' not in e
assert e['alphaErosionDefinition']['erosionMapChannelMixer']['constantValue']==[1,0,0,0]
d=dict(rate=e['rate']['constantValue'],lifetime=e['particleLifetime']['constantValue'],lifeRange=e['particleLifetime']['dynamics']['probabilityTables'][0]['keyValues'],
       linger=e['particleLinger'],birthScale=e['birthScale0']['constantValue'],scaleRange=e['birthScale0']['dynamics']['probabilityTables'][0]['keyValues'],
       color=e['Color']['constantValue'],colorTimes=e['Color']['dynamics']['times'],alphaValues=[v[3] for v in e['Color']['dynamics']['values']],
       scaleCurve=[v[0] for v in e['scale0']['dynamics']['values']],rotationRange=e['birthRotation0']['dynamics']['probabilityTables'][0]['keyValues'],
       softDistance=e['softParticleParams']['deltaIn']*.01,erosionFeatherOut=e['alphaErosionDefinition']['erosionFeatherOut'])
Path('src/content/hawkshot-smoke.ts').write_text('// Generated by tools/assets/export-hawkshot-smoke.py.\nexport const HAWKSHOT_SMOKE = '+json.dumps(d,indent=2)+' as const;\n')
print('Exported source Smoke_Trail parameters')
