def adrp_ldr_d_address(image, pc, load_pc, register=8):
    word, load = image.word(pc), image.word(load_pc)
    require(word & 0x9f00001f == 0x90000000 | register, 'Expected default ADRP register')
    require(load & 0xffc003ff == 0xfd400000 | (register << 5), 'Expected default LDR D0 base register')
    immediate = (((word >> 5) & 0x7ffff) << 2) | ((word >> 29) & 3)
    if immediate & (1 << 20): immediate -= 1 << 21
    return (pc & ~4095) + (immediate << 12) + (((load >> 10) & 4095) * 8)

def verify(image, core):
    for name, digest in PINS.items(): witness.pinned(Path(name), digest)
    # Local words first so a changed interpretation fails before inherited work.
    for pc, word, reading in WORDS:
        require(image.word(pc) == word, 'Height selected word differs: ' + reading)
    starts = function_starts(image.data, core['functionStarts'])
    spans = []
    for name, begin, end, digest in SPANS:
        slot = bisect.bisect_left(starts, begin)
        require(starts[slot:slot + 2] == [begin, end], 'Height function bounds differ: ' + name)
        raw = image.at(begin, end - begin)
        require(witness.sha(raw) == digest, 'Height function bytes differ: ' + name)
        spans.append({'name': name, 'start': hex(begin), 'next': hex(end), 'bytes': len(raw), 'sha256': digest, 'hex': raw.hex()})
    fields = []
    for name, pc, offset, wrapper in FIELDS:
        row = {'name': name, 'hash': hex(witness.fnv(name)), 'hashPair': [hex(pc), hex(pc + 4)]}
        image.pair(row); image.movz(pc + 8, 2, offset)
        require(image.branch(pc + 20) == wrapper, 'Height field wrapper differs')
        fields.append({**row, 'offset': offset, 'wrapper': hex(wrapper), 'namesAreFnvCandidates': True})
    for name, pc, size in [('GravityHeightSolver', 0x100acfbfc, 24), ('FixedSpeedMovement', 0x100ad06c0, 96)]:
        image.pair({'name': name, 'hash': hex(witness.fnv(name)), 'hashPair': [hex(pc), hex(pc + 4)]})
