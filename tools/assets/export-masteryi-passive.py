"""Project frozen Double Strike declarations and its explicit source pose binding.

Counter transitions and native caller/proc timing are not recovered. Existing
differing output is never overwritten. Guards remain active under Python -O.
"""
import argparse
import hashlib
import json
import runpy
from pathlib import Path

source = runpy.run_path(str(Path(__file__).with_name('export-masteryi-declarations.py')))
ROOT, require = source['ROOT'], source['require']
PASSIVE = 'Characters/MasterYi/Spells/MasterYiPassiveAbility/MasterYiPassive'
CHILD = 'Characters/MasterYi/Spells/MasterYiPassiveAbility/MasterYiDoubleStrike'


def generate():
    pin, _ = source['load']()
    records = pin['records']
    parent, child = records[PASSIVE]['mSpell'], records[CHILD]['mSpell']
    values = {row['name']: row['values'] for row in parent['DataValues']}
    require(values == {'StackDuration': [4.0]*7, 'AttackCount': [4.0]*7},
            'Passive count/duration changed')
    require(parent['mSpellCalculations']['TotalDamage'] == {
        'mSimpleTooltipCalculationDisplay': 6,
        'mFormulaParts': [{'mStat': 2, 'mCoefficient': 0.5,
                           '__type': 'StatByCoefficientCalculationPart'}],
        '__type': 'GameCalculation',
    }, 'Passive damage formula changed')
    root = records[source['ROOT_RECORD']]
    require(records['Characters/MasterYi/Spells/MasterYiPassiveAbility']['mChildSpells'][2] == CHILD
            and root['extraSpellsList'][0] == CHILD
            and root['extraAttacks'][2]['mAttackName'] == 'MasterYiDoubleStrike',
            'Secondary bindings changed')
    require(child['canCastWhileDisabled'] is True
            and child['mUseAutoattackCastTimeData'] == {'__type': 'UseAutoattackCastTimeData'},
            'Secondary capabilities changed')
    require(child['mAnimationName'] == 'Passive'
            and child['spellCastTime'] == 0.22499999403953552
            and child['castFrame'] == 7, 'Secondary animation/timing declarations changed')
    require('mSpellCalculations' not in child and 'DataValues' not in child,
            'Secondary acquired its own calculations')
    model_bytes = (ROOT / 'docs/reference/masteryi-model.json').read_bytes()
    require(hashlib.sha256(model_bytes).hexdigest() ==
            '4295bceeba96cfb15e006d392e7d0f3c480bb51bf8cff8872a9c39fc9873c7ce',
            'Model declaration pin changed')
    model = json.loads(model_bytes)
    skin = model['skin']['data']['Characters/MasterYi/Skins/Skin0']
    graph = model['animations']['data'][skin['skinAnimationProperties']['animationGraphData']]
    require(graph['mClipDataMap']['Passive'] == {
        'mClipNameList': ['{85dac0b3}', '{c722c9e7}'], '__type': 'ParallelClipData'
    }, 'Passive parallel binding changed')
    pose = graph['mClipDataMap']['{85dac0b3}']
    require(pose['__type'] == 'AtomicClipData' and pose['mTrackDataName'] == 'Default',
            'Passive default pose changed')
    meta = json.loads((ROOT / 'public/assets/models/masteryi-base.json').read_bytes())
    exported = next(c for c in meta['clips'] if c['name'] == 'entry_85dac0b3')
    require(exported['state'] == '{85dac0b3}' and exported['source'] ==
            pose['mAnimationResourceData']['mAnimationFilePath'].lower(),
            'Exported Passive pose differs')
    data = dict(attackCount=4, stackDurationSeconds=4, damageCoefficient=0.5,
                rawStatId=2, canCastWhileDisabled=True, usesAutoattackCastTimeData=True,
                animationName='Passive', defaultPoseClip='entry_85dac0b3',
                legacySpellCastTimeSeconds=child['spellCastTime'], legacyCastFrame=child['castFrame'],
                declaration=PASSIVE, secondaryDeclaration=CHILD)
    return ('// Generated by tools/assets/export-masteryi-passive.py.\n'
            '// Source declarations; native caller/counter/proc timing remains unresolved.\n'
            'export const MASTER_YI_PASSIVE = ' + json.dumps(data, indent=2) + ' as const;\n').encode()


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source['publish'](generate(), ROOT / 'src/content/masteryi-passive.ts', args.check)
    print('Verified Double Strike count/duration, damage declaration, child capabilities and Passive pose.')
