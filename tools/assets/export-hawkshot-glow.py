"""Export the two pinned Hawkshot background quads and losslessly decoded glow texture."""
from pathlib import Path
from io import BytesIO
import hashlib
import json
from PIL import Image
from cdtb.export import TexConverter

pin_path = Path('docs/reference/hawkshot-effects.json')
pin = json.loads(pin_path.read_text())
record = 'Characters/Ashe/Skins/Skin0/Particles/Ashe_Base_E_mis'
emitters = pin['records'][record]['data']['complexEmitterDefinitionData']
layers = [next(e for e in emitters if e['emitterName'] == name)
          for name in ['Background_Arrow', 'Background_Arrow1']]
source = layers[0]['texture'].lower()
entry = next(f for f in pin['extraction']['files'] if f['path'] == source)
raw = (Path('.cache/hawkshot-sources') / source).read_bytes()
assert len(raw) == entry['bytes'] and hashlib.sha256(raw).hexdigest() == entry['sha256']
image = Image.open(BytesIO(TexConverter.tex_to_dds(raw))).convert('RGBA')
output = Path('public/assets/effects/hawkshot-glow.png')
image.save(output)
assert Image.open(output).convert('RGBA').tobytes() == image.tobytes()
profiles = []
for e in layers:
    assert e['texture'].lower() == source
    assert e['primitive']['__type'] == 'VfxPrimitiveArbitraryQuad'
    assert e['isSingleParticle'] == e['isUniformScale'] == 1
    assert e['bindWeight']['constantValue'] == 1
    assert e['blendMode'] in [1, 4]
    assert 'texDiv' not in e and 'frameRate' not in e
    profiles.append(dict(name=e['emitterName'], delay=e['timeBeforeFirstEmission'],
                         lifetime=e['particleLifetime']['constantValue'],
                         offset=e['SpawnShape']['emitOffset'], color=e['Color']['constantValue'],
                         birthScale=e['birthScale0']['constantValue'], scale=e['scale0']['constantValue'],
                         blendMode=e['blendMode'], renderOrder=e['pass']))
Path('src/content/hawkshot-glow.ts').write_text(
    '// Generated by tools/assets/export-hawkshot-glow.py.\n'
    + 'export const HAWKSHOT_GLOW = ' + json.dumps(profiles, indent=2) + ' as const;\n')
Path('docs/reference/hawkshot-glow.json').write_text(json.dumps(dict(
    definitionsSha256=hashlib.sha256(pin_path.read_bytes()).hexdigest(), record=record,
    source=entry, emitters=layers,
    adapterEvidence=[dict(url='https://github.com/TheKillerey/ReyEngine/blob/cdf014d0b584f65b579211b522c5ed1dfe5687a5/src/ReyEngine.Rendering/Vfx/' + name,
        sha256=hashlib.sha256((Path('.cache/rey') / name).read_bytes()).hexdigest())
        for name in ['VfxParticleRenderer.cs', 'VfxParticleSimulator.cs']],
    texture=dict(path=str(output), size=list(image.size),
    rgbaSha256=hashlib.sha256(image.tobytes()).hexdigest(),
    sha256=hashlib.sha256(output.read_bytes()).hexdigest())), indent=2) + '\n')
print(f'Verified two source emitters and {image.width}x{image.height} RGBA texture ({output.stat().st_size} bytes)')
