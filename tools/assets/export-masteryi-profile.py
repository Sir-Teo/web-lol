"""Export the development Master Yi NPC profile from checked source declarations.

The local policy explicitly selects BIN AD growth despite the unresolved public
client disagreement. No native attack timing or critical policy is recovered.
"""
import argparse
import json
import runpy
from pathlib import Path

declarations = runpy.run_path(str(Path(__file__).with_name('export-masteryi-declarations.py')))
ROOT, require = declarations['ROOT'], declarations['require']


def generate():
    pin, dd = declarations['load']()
    projection = declarations['project'](pin, dd)
    values = {row['name']: row['sourceValue'] for row in projection['stats']}
    values['attackSpeedGrowth'] /= 100
    root = projection['character']['declaration']
    for field in ['attackSpeedRatio', 'selectionRadius', 'selectionHeight',
                  'pathfindingCollisionRadius', 'attackDelayCastOffsetPercent']:
        values[field] = (root['attackSpeedRatioModifiable']['baseValue'] if field == 'attackSpeedRatio'
                         else root['basicAttack']['mAttackDelayCastOffsetPercent']
                         if field == 'attackDelayCastOffsetPercent' else root[field])
    for name in ['MasterYiBasicAttack', 'MasterYiBasicAttack2', 'MasterYiCritAttack']:
        spell = pin['records'][f'Characters/MasterYi/Spells/{name}']['mSpell']
        require('mMissileSpec' not in spell, 'Ordinary melee attack gained a missile specification')
    # Explicit local melee-contact policy, not a recovered native contact callback.
    values['missileSpeed'] = 0
    values['rawCriticalDamageMultiplier'] = root['critDamageMultiplier']
    require(values['rawCriticalDamageMultiplier'] == 2, 'Raw critical multiplier changed')
    require(values['damageGrowth'] == 2.5 and dd['stats']['attackdamageperlevel'] == 0,
            'Explicit local AD-growth choice changed')
    return ('// Generated by tools/assets/export-masteryi-profile.py; see docs/MASTER-YI.md.\n'
            '// Melee contact and shared windup are local policies, not native callbacks.\n'
            '// Development policy uses BIN growth 2.5; Data Dragon 0 remains unresolved.\n'
            'export const MASTER_YI = ' + json.dumps(values, indent=2, allow_nan=False) + ' as const;\n').encode()


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    declarations['publish'](generate(), ROOT / 'src/content/masteryi-progression.ts', args.check)
    print('Verified Master Yi development profile; explicit BIN AD growth, no spell kit generated.')
