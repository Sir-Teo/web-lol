"""Verify and export the source endpoint Aurora texture and parameters."""
from pathlib import Path
from io import BytesIO
import hashlib,json
from PIL import Image
from cdtb.export import TexConverter
hash_bytes=lambda b:hashlib.sha256(b).hexdigest()
pin_path=Path('docs/reference/hawkshot-effects.json');pin=json.loads(pin_path.read_text())
record='Characters/Ashe/Skins/Skin0/Particles/Ashe_Base_E_tar_explode'
e=next(e for e in pin['records'][record]['data']['complexEmitterDefinitionData'] if e['emitterName']=='Aurora')
assert e['isSingleParticle']==1 and e['primitive']['__type']=='VfxPrimitiveArbitraryQuad'
assert e['blendMode']==4 and 'timeBeforeFirstEmission' not in e and 'isUniformScale' not in e
assert e['Color']['dynamics']['times']==[0,.5,1]
source=next(f for f in pin['extraction']['files'] if f['path']==e['texture'].lower())
raw=(Path('.cache/hawkshot-sources')/source['path']).read_bytes()
assert len(raw)==source['bytes'] and hash_bytes(raw)==source['sha256']
im=Image.open(BytesIO(TexConverter.tex_to_dds(raw))).convert('RGBA')
path=Path('public/assets/effects/hawkshot-arrival-core.png');im.save(path)
assert Image.open(path).convert('RGBA').tobytes()==im.tobytes()
data=dict(lifetime=e['particleLifetime']['constantValue'],lifeRange=e['particleLifetime']['dynamics']['probabilityTables'][0]['keyValues'],
          velocity=e['birthVelocity']['constantValue'],drag=e['birthDrag']['constantValue'],offset=e['EmitterPosition']['constantValue'],
          scale=e['birthScale0']['constantValue'],rotation=e['birthRotation0']['constantValue'],birthColor=e['birthColor']['constantValue'],
          color=e['Color']['constantValue'],alphaTimes=e['Color']['dynamics']['times'],alphaValues=[v[3] for v in e['Color']['dynamics']['values']],renderOrder=e['pass'])
Path('src/content/hawkshot-arrival.ts').write_text('// Generated by tools/assets/export-hawkshot-arrival.py.\nexport const HAWKSHOT_ARRIVAL = '+json.dumps(data,indent=2)+' as const;\n')
Path('docs/reference/hawkshot-arrival.json').write_text(json.dumps(dict(definitionsSha256=hash_bytes(pin_path.read_bytes()),record=record,emitter=e,texture=dict(source=source,path=str(path),dimensions=list(im.size),bytes=path.stat().st_size,sha256=hash_bytes(path.read_bytes()),rgbaSha256=hash_bytes(im.tobytes()))),indent=2)+'\n')
print(f'Verified endpoint Aurora and {im.width}x{im.height} texture ({path.stat().st_size} bytes)')
