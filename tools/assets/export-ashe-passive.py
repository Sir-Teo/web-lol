"""Verify standard Ashe passive values, excluding mode overrides."""
import hashlib
import json
from pathlib import Path

pin = json.loads(Path('docs/reference/ashe-passive.json').read_text())
raw = Path('.cache/ashe-16.18.json').read_bytes()
assert hashlib.sha256(raw).hexdigest() == pin['sha256']
record = json.loads(raw)[pin['record']]
assert record == pin['data']
strings_raw = Path('.cache/lol-strings-16.18.json').read_bytes()
assert hashlib.sha256(strings_raw).hexdigest() == pin['tooltips']['sha256']
strings = json.loads(strings_raw)['entries']
assert all(strings[key] == value for key, value in pin['tooltips']['entries'].items())
spell = record['mSpell']
part = spell['mSpellCalculations']['SlowAmount']['mFormulaParts'][0]
assert part['__type'] == 'ByCharLevelInterpolationCalculationPart'
duration = next(v['values'] for v in spell['DataValues'] if v['name'] == 'SlowDuration')
assert len(set(duration)) == 1
data = {'slowAtLevel1': round(part['mStartValue'], 6),
        'slowAtLevel18': round(part['mEndValue'], 6), 'durationSeconds': duration[0]}
critical = spell['mSpellCalculations']['EmpoweredSlowAmount']['mFormulaParts'][0]
assert critical['__type'] == 'ByCharLevelInterpolationCalculationPart'
data['criticalSlowAtLevel1'] = round(critical['mStartValue'], 6)
data['criticalSlowAtLevel18'] = round(critical['mEndValue'], 6)
Path('src/content/ashe-passive.ts').write_text(
    '// Generated by tools/assets/export-ashe-passive.py.\n'
    + 'export const ASHE_PASSIVE = ' + json.dumps(data, indent=2) + ' as const;\n')
print('Verified standard Ashe passive and exported basic slow scaling')
