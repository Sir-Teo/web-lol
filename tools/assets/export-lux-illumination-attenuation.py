"""Preserve source attenuation and sample the pinned parser's scaling interpretation."""
from pathlib import Path
import argparse,hashlib,json,math,re,subprocess,sys
REVISION='71654ed1a2c4642894bd7e7ed79eba66986fb770'
assert subprocess.check_output(['git','-C','.tools/wwiser','rev-parse','HEAD'],text=True).strip()==REVISION
sys.path.insert(0,'.tools/wwiser')
from wwiser.generator.render.bnode_rtpc import _AkGraph,_AkGraphPoint
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--effect',choices=('illumination','binding'),default='illumination')
effect=parser.parse_args().effect
source_path=Path(f'docs/reference/lux-{effect}-audio.json');source=json.loads(source_path.read_text())
nodes={n['id']:n for n in source['nodes']}
assert all(b['version']==145 for b in json.loads(Path('docs/reference/lux-audio-inventory.json').read_text())['banks'])
fields=nodes[339248780]['parameters']
def value(fields,suffix):
 matches=[p for p in fields if p[0].endswith(suffix)]
 assert len(matches)==1,(suffix,len(matches))
 return float(matches[0][2])
assert value(fields,'/NumCurves')==1
assert value(fields,'/bIsConeEnabled')==0
assert value(fields,'/bIsHeightSpreadEnabled')==0
scaling=int(value(fields,'/eScaling'));assert scaling==2
root=nodes[413871746]['parameters']
assert value(root,'/bPositioningInfoOverrideParent')==1
assert value(root,'/bEnableAttenuation')==1
assert value(root,'/OverrideBusId')==1259461568
for n in source['nodes']:
 if n['type'] in ('CAkSound','CAkRanSeqCntr') or n['id']==(1148 if effect=='illumination' else 1150):
  assert value(n['parameters'],'/bPositioningInfoOverrideParent')==0
points=[]
for p in fields:
 if not p[0].endswith('/From'):continue
 prefix=p[0][:-4]
 points.append(dict(distance=float(p[2]),storedValue=value(fields,prefix+'To'),interpolation=int(value(fields,prefix+'Interp'))))
assert len(points)==int(value(fields,'/ulSize'))==6
assert all(a['distance']<b['distance'] for a,b in zip(points,points[1:]))
routing=[int(p[2]) for p in fields if re.search(r'/curveToUse\[\d+\]$',p[0])]
profile=dict(attenuationId=339248780,parentMixerId=413871746,unresolvedOutputBusId=1259461568,
            bankVersion=145,scaling=scaling,curveToUse=routing,points=points)
Path(f'src/content/lux-{effect}-attenuation.ts').write_text('// Generated by tools/assets/export-lux-illumination-attenuation.py; distances are source units.\nexport const LUX_'+effect.upper()+'_ATTENUATION = '+json.dumps(profile,indent=2)+' as const;\n')
subprocess.run(['npx','prettier','--write',f'src/content/lux-{effect}-attenuation.ts'],check=True,stdout=subprocess.DEVNULL)
# Execute the independent pinned implementation, not a duplicate JS formula.
graph=_AkGraph(None,scaling);graph.version=145
for p in points:
 point=_AkGraphPoint(None);point.x=p['distance'];point.y=p['storedValue'];point.i=p['interpolation'];graph.points.append(point)
distances=set(range(0,3501,50))
for p in points:
 distances.update([max(0,p['distance']-0.001),p['distance'],p['distance']+0.001])
for a,b in zip(points,points[1:]):distances.add((a['distance']+b['distance'])/2)
samples=[dict(distance=d,db=graph.get(d),amplitude=10**(graph.get(d)/20)) for d in sorted(distances)]
result=dict(sourceGraphSha256=hashlib.sha256(source_path.read_bytes()).hexdigest(),parserRevision=REVISION,
    parserFileSha256=hashlib.sha256(Path('.tools/wwiser/wwiser/generator/render/bnode_rtpc.py').read_bytes()).hexdigest(),
    profile=profile,samples=samples,
    status='Pinned parser interpretation only. Native listener position, distance scale, shared bus and curve/mixing parity remain unverified; not connected to runtime audio.')
Path(f'docs/reference/lux-{effect}-attenuation.json').write_text(json.dumps(result,indent=2)+'\n')
print(json.dumps([s for s in samples if s['distance'] in (0,1750,2000,2300,2750,3000)]))
