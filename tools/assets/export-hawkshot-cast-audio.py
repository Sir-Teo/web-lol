"""Ship the verified float cast variants and derive timing/gain from bank graph."""
from pathlib import Path
import hashlib
import json
import subprocess

read=lambda p: json.loads(Path(p).read_text())
graph=read('docs/reference/hawkshot-audio.json')
decoded=read('docs/reference/hawkshot-audio-decoded.json')
assert decoded['sourceGraphSha256']==hashlib.sha256(Path('docs/reference/hawkshot-audio.json').read_bytes()).hexdigest()
event=next(e for e in graph['events'] if e['name']=='Play_sfx_Ashe_AsheSpiritOfTheHawk_OnCast')
nodes={n['id']:n for n in graph['nodes']}
def prop(node,label):
 fields=nodes[node]['parameters']
 pid=next(p for p in fields if p[0].endswith('/pID') and f'[{label}]' in (p[3] or ''))
 return float(next(p[2] for p in fields if p[0]==pid[0][:-3]+'pValue'))
assert event['actions']==[790390000]
container=3432
assert any(p[0].endswith('/idExt') and int(p[2])==container for p in nodes[event['actions'][0]]['parameters'])
variants=[]
for identity in event['mediaIds']:
 media=next(m for m in decoded['media'] if m['id']==identity)
 raw=Path(f'.cache/hawkshot-audio-decoded/{identity}.wav').read_bytes()
 assert hashlib.sha256(raw).hexdigest()==media['wavSha256']
 target=Path(f'public/assets/audio/hawkshot-cast-{identity}.wav')
 target.parent.mkdir(parents=True,exist_ok=True)
 target.write_bytes(raw)
 variants.append(dict(id=identity,url='/'+str(target.relative_to('public')),sha256=media['wavSha256']))
profile=dict(eventId=event['id'],delaySeconds=prop(event['actions'][0],'DelayTime')/1000,
             gainDb=prop(container,'MakeUpGain'),variants=variants)
Path('src/content/hawkshot-cast-audio.ts').write_text('// Generated by tools/assets/export-hawkshot-cast-audio.py; source bank parameters.\nexport const HAWKSHOT_CAST_AUDIO = '+json.dumps(profile,indent=2)+' as const;\n')
subprocess.run(['npx', 'prettier', '--write', 'src/content/hawkshot-cast-audio.ts'], check=True, stdout=subprocess.DEVNULL)
print(json.dumps(profile))
