"""Project frozen standard Highlander data without fabricating its missing formulas.

Activation, stat scaling, immunity and takedown dispatch remain controller policies.
--output permits isolated preparation before runtime integration. Differing
existing output is never overwritten; guards survive Python optimization.
"""
import argparse
import json
import runpy
from pathlib import Path

source = runpy.run_path(str(Path(__file__).with_name('export-masteryi-declarations.py')))
ROOT, require = source['ROOT'], source['require']
SPELL = 'Characters/MasterYi/Spells/HighlanderAbility/Highlander'


def generate():
    pin, dd = source['load']()
    records = pin['records']
    spell = records[SPELL]['mSpell']
    require(records[source['ROOT_RECORD']]['spells'][3] == SPELL, 'R spellbook binding changed')
    require(records['Characters/MasterYi/Spells/HighlanderAbility']['mChildSpells'] == [
        SPELL, 'Characters/MasterYi/Spells/HighlanderAbility/HighlanderSpellPassive'
    ], 'R passive binding changed')
    values = {row['name']: row['values'] for row in spell['DataValues']}
    require(values == {
        'RDuration': [7.0]*7,
        'RASBonus': [5.0, 25.0, 45.0, 65.0, 85.0, 105.0, 125.0],
        'RMSBonus': [30.0, 40.0, 50.0, 60.0, 70.0, 80.0, 90.0],
        'RKillAssistExtension': [7.0]*7,
        'RCooldownRefund': [0.699999988079071]*7,
    }, 'Standard R named values changed')
    public = dd['spells'][3]
    require(public['id'] == 'Highlander' and public['maxrank'] == 3
            and public['cost'] == [100]*3 and public['cooldown'] == [85]*3,
            'Public identity/ranks/resources changed')
    require(spell['mana'] == [100.0]*5 + [0.0] and spell['cooldownTime'] == [85.0]*7,
            'Source mana/cooldown changed')
    require('mSpellCalculations' not in spell, 'Missing R calculation table changed')
    require(spell['mAnimationName'] == '' and spell['mTargetingTypeData']['__type'] == 'Self'
            and spell['mCantCancelWhileWindingUp'] is True
            and spell['spellCastTime'] == 0.4043000042438507,
            'Empty animation/self/windup declarations changed')
    require(spell['mSpellTags'] == ['Trait_Ultimate', 'Trait_AttackBuff_Duration'],
            'R spell traits changed')
    data = dict(name=public['name'], description=public['description'], icon=public['id'],
                durationSeconds=values['RDuration'][0],
                attackSpeedPercentByRank=values['RASBonus'][1:4],
                movementSpeedPercentByRank=values['RMSBonus'][1:4],
                killAssistExtensionSeconds=values['RKillAssistExtension'][0],
                basicCooldownRefundFraction=values['RCooldownRefund'][0],
                manaByRank=spell['mana'][:3], cooldownSecondsByRank=spell['cooldownTime'][1:4],
                sourceCalculations=None, sourceAnimationName=spell['mAnimationName'],
                authoredCastSeconds=spell['spellCastTime'], authoredCannotCancelWindup=True,
                declaration=SPELL)
    return ('// Generated by tools/assets/export-masteryi-r.py.\n'
            '// No source calculation table; native activation/stat/takedown dispatch is unresolved.\n'
            'export const MASTER_YI_R = ' + json.dumps(data, indent=2) + ' as const;\n').encode()


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--output', type=Path, default=ROOT / 'src/content/masteryi-r.ts')
    args = parser.parse_args()
    source['publish'](generate(), args.output, args.check)
    print('Verified standard Highlander ranks, duration/extension/refund, resources, empty animation and omitted formula table.')
