"""Export strict birth-only profiles from the verified, hash-resolved target record."""
from pathlib import Path
import hashlib
import json
import subprocess

pin_path=Path('docs/reference/lux-binding-target-vfx.json')
audit_path=Path('docs/reference/lux-binding-target-fields.json')
audit=json.loads(audit_path.read_text())
assert audit['sourcePinSha256']==hashlib.sha256(pin_path.read_bytes()).hexdigest()
assert audit['readerDefaults']['particleLifetimeSeconds']==3

def vector(value): return value if isinstance(value,list) else [value]
def field_hash(name):
    value=2166136261
    for byte in name.lower().encode('ascii'): value=((value^byte)*16777619)&0xffffffff
    return '{%08x}'%value

def absent(record, names):
    keys={key.lower() for key in record}
    for name in names:
        assert name.lower() not in keys and field_hash(name) not in keys, name

def birth(value, default):
    dynamics=value.get('dynamics')
    if dynamics: assert dynamics['times']==[0] and len(dynamics['values'])==1
    base=vector(dynamics['values'][0] if dynamics else value.get('constantValue',default))
    tables=dynamics.get('probabilityTables') if dynamics else None
    probabilities=None if tables is None else [dict(single=t.get('singleValue',1),times=t.get('keyTimes',[]),values=t.get('keyValues',[])) for t in tables]
    for table in probabilities or []:
        assert len(table['times'])==len(table['values'])
        assert all(a<b for a,b in zip(table['times'],table['times'][1:]))
    return dict(value=base,probabilities=probabilities)

profiles=[]
for index,e in enumerate(audit['resolvedDefinition']['complexEmitterDefinitionData']):
    assert set(e['rate'])=={'constantValue','__type'}
    assert e.get('timeBeforeFirstEmission',0)==0
    assert not e.get('disabled',False)
    spawn=e.get('SpawnShape',{})
    # Static motion deliberately supports only the authored constant birth velocity.
    # Fail on future motion fields, including their unresolved hash representation.
    absent(e, ['velocity','acceleration','worldAcceleration','birthAcceleration',
        'drag','birthDrag','birthOrbitalVelocity','orbitalVelocity','translationOverride'])
    absent(spawn, ['birthTranslation'])
    assert len(spawn.get('emitRotationAngles',[]))<=1
    assert not spawn or spawn['__type'] in ('VfxShapeLegacy','{ee39916f}')
    if spawn.get('__type')=='{ee39916f}': assert set(spawn)=={'__type','emitOffset'}
    offset=spawn.get('emitOffset',{})
    if isinstance(offset,list): offset={'constantValue':offset}
    profiles.append(dict(index=index,name=e['emitterName'],rate=e['rate']['constantValue'],
        emitterLife=e['lifetime'],single=bool(e.get('isSingleParticle',False)),
        life=birth(e.get('particleLifetime',{}),3),
        size=birth(e.get('birthScale0',{}),[1,1,1]),
        rotation=birth(e.get('birthRotation0',{}),[0,0,0]),
        spin=birth(e.get('birthRotationalVelocity0',{}),[0,0,0]),
        velocity=birth(e.get('birthVelocity',{}),[0,0,0]),
        color=birth(e.get('birthColor',{}),[1,1,1,1]),
        emitterPosition=birth(e.get('EmitterPosition',{}),[0,0,0]),
        spawnType=spawn.get('__type'),spawnOffset=birth(offset,[0,0,0]),
        spawnAngles=[birth(v,0) for v in spawn.get('emitRotationAngles',[])],
        spawnAxes=spawn.get('emitRotationAxes',[])))
    assert len(profiles[-1]['spawnAngles'])==len(profiles[-1]['spawnAxes'])
assert len(profiles)==11
out=Path('src/content/lux-binding-target-births.ts')
out.write_text('// Generated by tools/assets/export-lux-binding-target-births.py.\n'
    '// Birth values only; source axes/offsets are not transformed here.\n'
    'export const LUX_BINDING_TARGET_BIRTHS = '+json.dumps(profiles,indent=2)+' as const;\n')
subprocess.run(['npx','prettier','--write',str(out)],check=True,stdout=subprocess.DEVNULL)
print('Exported eleven target birth profiles with complete per-axis probability tables.')
