"""Pin the complete endpoint smoke emitter and its normalized playback profile."""
from pathlib import Path
import hashlib, json
path = Path('docs/reference/hawkshot-effects.json')
source = json.loads(path.read_text())
record = 'Characters/Ashe/Skins/Skin0/Particles/Ashe_Base_E_tar_explode'
e = next(e for e in source['records'][record]['data']['complexEmitterDefinitionData'] if e['emitterName'] == 'smoke')
assert e['primitive']['__type'] == 'VfxPrimitiveArbitraryQuad' and e['isDirectionOriented'] == 1
assert e['blendMode'] == 4 and e['texDiv'] == [2, 2] and e['numFrames'] == 4
texture = next(t for t in json.loads(Path('docs/reference/hawkshot-sprites.json').read_text())['textures'] if t['source']['path'] == e['texture'].lower())
assert hashlib.sha256(Path(texture['path']).read_bytes()).hexdigest() == texture['sha256']
p = dict(duration=e['lifetime'], rate=e['rate']['dynamics']['values'],
    life=e['particleLifetime']['constantValue'], lifeRange=e['particleLifetime']['dynamics']['probabilityTables'][0]['keyValues'],
    velocity=e['birthVelocity']['constantValue'], velocityRange=e['birthVelocity']['dynamics']['probabilityTables'][0]['keyValues'],
    drag=e['birthDrag']['constantValue'], radius=[v[0] for v in e['SpawnShape']['emitOffset']['dynamics']['values']],
    offset=e['EmitterPosition']['constantValue'], rotation=e['birthRotation0']['constantValue'], scale=e['birthScale0']['constantValue'],
    growth=e['scale0']['dynamics']['values'], color=e['Color']['dynamics']['values'][0])
Path('src/content/hawkshot-radial.ts').write_text('// Generated by tools/assets/export-hawkshot-radial.py.\nexport const HAWKSHOT_RADIAL = '+json.dumps(p,indent=2)+' as const;\n')
Path('docs/reference/hawkshot-radial.json').write_text(json.dumps(dict(definitionsSha256=hashlib.sha256(path.read_bytes()).hexdigest(),record=record,emitter=e,texture=texture,profile=p),indent=2)+'\n')
print('Verified radial smoke emitter and reused atlas')
