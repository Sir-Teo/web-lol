"""Verify spellbook-selected Hawkshot and export standard ammunition values."""
import hashlib
import json
from pathlib import Path

pin = json.loads(Path('docs/reference/ashe-e.json').read_text())
raw = Path('.cache/ashe-16.18.json').read_bytes()
assert hashlib.sha256(raw).hexdigest() == pin['sha256']
source = json.loads(raw)
assert source[pin['root']]['spells'][pin['spellIndex']] == pin['spell']
assert all(source[key] == record for key, record in pin['records'].items())
strings_raw = Path('.cache/lol-strings-16.18.json').read_bytes()
assert hashlib.sha256(strings_raw).hexdigest() == pin['tooltips']['sha256']
strings = json.loads(strings_raw)['entries']
assert all(strings[key] == value for key, value in pin['tooltips']['entries'].items())
spell = source[pin['spell']]['mSpell']
assert len(set(spell['mMaxAmmo'])) == 1
assert spell['cooldownTime'] == spell['Cooldown']['values']
assert len(set(spell['cooldownTime'])) == 1
recharge = spell['mAmmoRechargeTime'][1:6]
assert recharge == next(v['values'][1:6] for v in spell['DataValues'] if v['name'] == 'BaseCooldown')
data = {
    'maximumCharges': spell['mMaxAmmo'][1],
    'castCooldownSeconds': spell['cooldownTime'][1],
    'rechargeSecondsByRank': recharge,
}
Path('src/content/ashe-e.ts').write_text(
    '// Generated by tools/assets/export-ashe-e.py.\n'
    + 'export const ASHE_E = ' + json.dumps(data, indent=2) + ' as const;\n')
print('Verified Hawkshot charge capacity, cast cooldown and normal-rank recharge')
