"""Export both source flight layers, their gain and matching stop transitions."""
from pathlib import Path
import hashlib,json,subprocess
p=Path('docs/reference/hawkshot-audio.json');graph=json.loads(p.read_text())
decoded=json.loads(Path('docs/reference/hawkshot-audio-decoded.json').read_text())
assert decoded['sourceGraphSha256']==hashlib.sha256(p.read_bytes()).hexdigest()
nodes={n['id']:n for n in graph['nodes']}
def prop(node,label):
 fields=nodes[node]['parameters']
 pid=next(p for p in fields if p[0].endswith('/pID') and f'[{label}]' in (p[3] or ''))
 return float(next(p[2] for p in fields if p[0]==pid[0][:-3]+'pValue'))
def target(action,expected):
 assert any(p[0].endswith('/idExt') and int(p[2])==expected for p in nodes[action]['parameters'])
play=next(e for e in graph['events'] if e['name']=='Play_sfx_Ashe_AsheSpiritOfTheHawk_OnMissileLaunch')
stop=next(e for e in graph['events'] if e['name']=='Stop_sfx_Ashe_AsheSpiritOfTheHawk_OnMissileLaunch')
assert play['actions']==[270466057,886269433] and stop['actions']==[754547015,405725596]
for action,dest in ((270466057,3429),(886269433,921284325),(754547015,3429),(405725596,921284325)):target(action,dest)
assert prop(921284325,'Loop')==0
for action in stop['actions']:
 assert prop(action,'TransitionTime')==150
 assert any(p[0].endswith('/eFadeCurve') and p[2]=='4' for p in nodes[action]['parameters'])
assert any(p[0].endswith('/eRandomMode') and '[Shuffle]' in (p[3] or '') for p in nodes[3429]['parameters'])
def ship(identity,name):
 media=next(m for m in decoded['media'] if m['id']==identity)
 raw=Path(f'.cache/hawkshot-audio-decoded/{identity}.wav').read_bytes()
 assert hashlib.sha256(raw).hexdigest()==media['wavSha256']
 target=Path(f'public/assets/audio/hawkshot-flight-{name}.wav');target.parent.mkdir(parents=True,exist_ok=True);target.write_bytes(raw)
 return dict(id=identity,url='/'+str(target.relative_to('public')),sha256=media['wavSha256'])
profile=dict(eventId=play['id'],stopEventId=stop['id'],fadeSeconds=prop(754547015,'TransitionTime')/1000,
 fadeCurve=4,variantGainDb=prop(3429,'MakeUpGain'),loopGainDb=prop(921284325,'MakeUpGain'),
 variants=[ship(i,str(i)) for i in (695824710,725427454,761127030)],loop=ship(61040111,'loop'))
assert set(play['mediaIds'])=={v['id'] for v in profile['variants']}|{profile['loop']['id']}
Path('src/content/hawkshot-flight-audio.ts').write_text('// Generated by tools/assets/export-hawkshot-flight-audio.py.\nexport const HAWKSHOT_FLIGHT_AUDIO = '+json.dumps(profile,indent=2)+' as const;\n')
subprocess.run(['npx','prettier','--write','src/content/hawkshot-flight-audio.ts'],check=True,stdout=subprocess.DEVNULL)
print(json.dumps(profile))
