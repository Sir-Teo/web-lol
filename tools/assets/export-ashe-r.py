"""Verify the standard crystal arrow and export its acceleration constants."""
import hashlib
import json
from pathlib import Path

pin = json.loads(Path('docs/reference/ashe-r.json').read_text())
raw = Path('.cache/ashe-16.18.json').read_bytes()
assert hashlib.sha256(raw).hexdigest() == pin['sha256']
record = json.loads(raw)[pin['record']]
assert record == pin['data']
movement = record['mSpell']['mMissileSpec']['movementComponent']
assert movement['__type'] == 'AcceleratingMovement'
data = {'initialSpeed': movement['mInitialSpeed'], 'acceleration': movement['mAcceleration'],
        'maximumSpeed': movement['mMaxSpeed']}
visibility = record['mSpell']['mMissileSpec']['visibilityComponent']
assert visibility['__type'] == 'Defaultvisibility'
data['sightRadius'] = visibility['mPerceptionBubbleRadius']
cast_ranges = record['mSpell']['castRange']
assert len(set(cast_ranges)) == 1
data['range'] = cast_ranges[0]
for name, field in [('SlowRadius', 'splashRadius'), ('AoECoefficient', 'splashDamageMultiplier')]:
    values = next(v['values'] for v in record['mSpell']['DataValues'] if v['name'] == name)
    assert len(set(values)) == 1
    data[field] = values[0]
assert movement['mMinSpeed'] == data['initialSpeed'] < data['maximumSpeed']
Path('src/content/ashe-r.ts').write_text(
    '// Generated by tools/assets/export-ashe-r.py.\n'
    + 'export const ASHE_R = ' + json.dumps(data, indent=2) + ' as const;\n')
print('Verified crystal arrow source and exported accelerating movement')
