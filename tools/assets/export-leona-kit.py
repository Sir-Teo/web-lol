"""Export Leona's declared Rift values from retained inputs, without network access.

Run with --check to verify generated bytes without writing. Script behavior,
collision boundaries and native timing are deliberately not inferred here.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'docs/reference/leona'
PINS = {
    'character.json': '5b126053b2c47bef0922139094620ffbd03adb9ca2b3289cfd118980d8fb7d83',
    'character.bin': 'f1f8791e19d630afb968745c353b17ae2e0020f1d5e24f5a85db838528edd4f1',
    'names.json': '92eff387fddbd6188cb00cf879a68205b6f7902e386c3ec851038fbc920174dc',
    'ddragon-16.18.1.json': '1c8cafec74033be85ce2b6fd76e3916dddc2517445c9f6a66b9bee6cedaabc42',
}


def require(condition, message):
    if not condition:
        raise ValueError(message)


def finite(value):
    require(type(value) in (int, float) and math.isfinite(value), 'Nonfinite source value')
    return value


def generate():
    for name, digest in PINS.items():
        require(hashlib.sha256((SOURCE / name).read_bytes()).hexdigest() == digest,
                f'Frozen source changed: {name}')
    pin = json.loads((SOURCE / 'character.json').read_text())
    records = pin['records']
    require(records == json.loads((SOURCE / 'names.json').read_text()), 'Naming export differs')
    require(len(records) - 1 == 51 and records['__linked'] == [], 'Unexpected character closure')
    require(pin['sha256'] == PINS['names.json'], 'Naming provenance differs')
    require(pin['extraction']['referenceVersion'] == '16.18.8175716', 'Unexpected patch')
    require(pin['extraction']['files'] == [{
        'path': 'data/characters/leona/leona.bin', 'wadPathHash': 'b01c50a67cc60507',
        'sha256': PINS['character.bin'], 'bytes': 24399,
    }], 'Archive provenance differs')
    dd = json.loads((SOURCE / 'ddragon-16.18.1.json').read_text())
    require(dd['version'] == '16.18.1', 'Unexpected Data Dragon version')
    dd = dd['data']['Leona']
    root_path = 'Characters/Leona/CharacterRecords/Root'
    root = records[root_path]
    stat_fields = {
        'hp': ('baseHPModifiable', 'hp', 1),
        'hpGrowth': ('hpPerLevelModifiable', 'hpperlevel', 1),
        'damage': ('baseDamageModifiable', 'attackdamage', 1),
        'damageGrowth': ('damagePerLevelModifiable', 'attackdamageperlevel', 1),
        'armor': ('baseArmorModifiable', 'armor', 1),
        'armorGrowth': ('armorPerLevelModifiable', 'armorperlevel', 1),
        'magicResist': ('baseMR', 'spellblock', 1),
        'magicResistGrowth': ('mrPerLevel', 'spellblockperlevel', 1),
        'attackSpeed': ('attackSpeedModifiable', 'attackspeed', 1),
        'healthRegen': ('baseStaticHPRegenModifiable', 'hpregen', 5),
        'healthRegenGrowth': ('hpRegenPerLevelModifiable', 'hpregenperlevel', 5),
        'speed': ('baseMoveSpeedModifiable', 'movespeed', 1),
        'range': ('attackRangeModifiable', 'attackrange', 1),
        'attackSpeedGrowth': ('attackSpeedPerLevelModifiable', 'attackspeedperlevel', 1),
    }
    stats, stat_audit = {}, []
    for name, (field, dd_field, factor) in stat_fields.items():
        value = finite(root[field]['baseValue'])
        agrees = abs(value * factor - dd['stats'][dd_field]) < 1e-6
        require(agrees or name == 'damageGrowth', f'Stat conflict: {name}')
        stats[name] = value / 100 if name == 'attackSpeedGrowth' else value
        stat_audit.append(dict(output=name, field=field, sourceValue=value,
                               dataDragonField=dd_field, dataDragonValue=dd['stats'][dd_field],
                               dataDragonFactor=factor, agreesWithinFloat32Tolerance=agrees))
    require(stats['damageGrowth'] == 3 and dd['stats']['attackdamageperlevel'] == 0,
            'Expected AD-growth disagreement changed')
    resource = root['primaryAbilityResource']
    require(resource['arType'] == 0, 'Expected mana resource')
    for name, field, dd_field in [
        ('mana', '{726ee5cd}', 'mp'), ('manaGrowth', '{6216bf7b}', 'mpperlevel'),
        ('manaRegen', '{c4ab3550}', 'mpregen'),
        ('manaRegenGrowth', '{3a509002}', 'mpregenperlevel'),
    ]:
        value = finite(resource[field]['baseValue'])
        factor = 5 if 'Regen' in name else 1
        require(abs(value * factor - dd['stats'][dd_field]) < 1e-6, f'Resource conflict: {name}')
        stats[name] = value
        stat_audit.append(dict(output=name, field=f'primaryAbilityResource.{field}',
                               sourceValue=value, dataDragonField=dd_field,
                               dataDragonValue=dd['stats'][dd_field], dataDragonFactor=factor,
                               agreesWithinFloat32Tolerance=True))
    stats['attackSpeedRatio'] = finite(root['attackSpeedRatioModifiable']['baseValue'])
    for field in ['selectionRadius', 'selectionHeight', 'pathfindingCollisionRadius']:
        stats[field] = finite(root[field])
    # An omitted cast-offset scaling coefficient is not Garen's authored 0.5.
    require('mAttackDelayCastOffsetPercentAttackSpeedRatio' not in root['basicAttack'],
            'Attack-speed timing declaration changed')
    stats['attackDelayCastOffsetPercent'] = finite(root['basicAttack']['mAttackDelayCastOffsetPercent'])

    spells, spell_audit = {}, []
    for index, slot in enumerate(['q', 'w', 'e', 'r']):
        path = root['spells'][index]
        spell = records[path]['mSpell']
        client = dd['spells'][index]
        ranks = 3 if slot == 'r' else 5
        require(client['id'] == records[path]['ObjectName'], f'{slot}: spell identity')
        require(client['maxrank'] == ranks == spell['mClientData']['mTooltipData']['mLists']['LevelUp']['levelCount'],
                f'{slot}: rank count')
        cooldown = spell['cooldownTime'][1:ranks + 1]
        mana = spell['mana'][:ranks]
        display_range = spell.get('castRangeDisplayOverride', spell['castRange'])[:ranks]
        require(cooldown == spell['Cooldown']['values'][1:ranks + 1] == client['cooldown'],
                f'{slot}: cooldown rank indexing')
        require(mana == spell['manaValues']['values'][:ranks] == client['cost'],
                f'{slot}: mana rank indexing')
        require(display_range == client['range'], f'{slot}: display range')
        named = {v['name']: v['values'] for v in spell['DataValues']}
        require(len(named) == len(spell['DataValues']), f'{slot}: duplicate named value')
        require(all(len(v) == 7 for v in named.values()), f'{slot}: named rank arrays')
        for values in [cooldown, mana, *named.values()]:
            for value in values:
                finite(value)
        spells[slot] = dict(rankCount=ranks, manaByRank=mana, cooldownSecondsByRank=cooldown)
        spell_audit.append(dict(slot=slot, record=path, namedValues=named,
                                calculations=spell['mSpellCalculations'],
                                authoredCastTime=spell.get('mCastTime'),
                                legacySpellCastTime=spell['spellCastTime'],
                                animationName=spell['mAnimationName'],
                                castFrame=spell.get('castFrame'),
                                rawCastRange=spell['castRange'],
                                displayRange=display_range,
                                rawCastRadius=spell['castRadius'],
                                modeOverrides=spell.get('DataValuesModeOverride', {})))

        def by_rank(name):
            return named[name][1:ranks + 1]

        def constant(name):
            require(len(set(named[name])) == 1, f'{slot}: nonconstant {name}')
            return named[name][0]

        calculations = spell['mSpellCalculations']
        if slot in ('q', 'e'):
            parts = calculations['TotalDamageTooltip']['mFormulaParts']
            require(parts[0] == {'mDataValue': 'BaseDamage', '__type': 'NamedDataValueCalculationPart'},
                    f'{slot}: base damage calculation')
            require(set(parts[1]) == {'mCoefficient', '__type'}
                    and parts[1]['__type'] == 'StatByCoefficientCalculationPart',
                    f'{slot}: AP coefficient calculation')
            spells[slot].update(baseDamageByRank=by_rank('BaseDamage'),
                                abilityPowerRatio=parts[1]['mCoefficient'])
        if slot == 'q':
            require('Trait_AttackReset' in spell['mSpellTags'], 'Q reset declaration missing')
            spells[slot].update(stunSeconds=constant('StunDuration'), resetsAttackTimer=True)
            attack_path = 'Characters/Leona/Spells/LeonaShieldOfDaybreakAbility/LeonaShieldOfDaybreakAttack'
            attack = records[attack_path]['mSpell']
            require(attack['mCastTime'] == 0.25 and attack['canCastWhileDisabled']
                    and attack['mCantCancelWhileWindingUp'], 'Q attack declaration changed')
            spells[slot].update(authoredAttackCastSeconds=attack['mCastTime'],
                                attackCanReleaseWhileDisabled=attack['canCastWhileDisabled'],
                                attackCannotCancelWindup=attack['mCantCancelWhileWindingUp'])
            spell_audit[-1]['attackDeclaration'] = dict(record=attack_path,
                explicitCastTime=attack['mCastTime'], legacyCastTime=attack['spellCastTime'],
                legacyTotalTime=attack['spellTotalTime'],
                canCastWhileDisabled=attack['canCastWhileDisabled'],
                cannotCancelWindup=attack['mCantCancelWhileWindingUp'])
        if slot == 'w':
            for key, name in [('flatReductionByRank', 'FlatDamageReduction'),
                              ('baseDamageByRank', 'ExplosionBaseDamage'),
                              ('baseArmorByRank', 'ArmorBaseBonus'), ('baseMagicResistByRank', 'MRBaseBonus')]:
                spells[slot][key] = by_rank(name)
            require(named['ArmorBaseBonus'] == named['MRBaseBonus'], 'W base-resistance aliases differ')
            for calc, stat, output in [('BonusArmorTooltip', 1, 'bonusArmorRatio'),
                                       ('BonusMRTooltip', 6, 'bonusMagicResistRatio')]:
                parts = calculations[calc]['mFormulaParts']
                require(parts[0] == {'mDataValue': 'ArmorBaseBonus', '__type': 'NamedDataValueCalculationPart'},
                        f'W: unexpected {calc} base')
                require(parts[1] == dict(mStat=stat, mStatFormula=2, mCoefficient=0.20000000298023224,
                                        __type='StatByCoefficientCalculationPart'), f'W: {calc} scaling')
                spells[slot][output] = parts[1]['mCoefficient']
            require(calculations['TotalDamageTooltip']['mFormulaParts'] == [
                {'mDataValue': 'ExplosionBaseDamage', '__type': 'NamedDataValueCalculationPart'},
                {'mDataValue': 'APRatio', '__type': 'StatByNamedDataValueCalculationPart'},
            ], 'W damage calculation changed')
            spells[slot].update(abilityPowerRatio=constant('APRatio'),
                                flatReductionMaximumFraction=constant('FlatDamageReductionMax'),
                                resistanceSeconds=constant('ArmorMRDuration'),
                                displayRange=display_range[0], authoredCastRadius=spell['castRadius'][0])
        if slot == 'e':
            missile_path = 'Characters/Leona/Spells/LeonaZenithBladeAbility/LeonaZenithBladeMissile'
            missile = records[missile_path]['mSpell']
            spec = missile['mMissileSpec']
            movement = spec['movementComponent']
            require(movement['__type'] == 'FixedSpeedMovement' and not movement['mTracksTarget']
                    and movement['mProjectTargetToCastRange'], 'E missile movement changed')
            require(spec['mMissileWidth'] == missile['mLineWidth'] == 70
                    and movement['mSpeed'] == missile['missileSpeed'] == 2000,
                    'E child missile dimensions changed')
            require(spell['mCastTime'] == 0.25 and spell['mCantCancelWhileWindingUp'],
                    'E cast declarations changed')
            spells[slot].update(authoredCastSeconds=spell['mCastTime'],
                                castCannotCancelWindup=spell['mCantCancelWhileWindingUp'],
                                rootSeconds=constant('RootDuration'), displayRange=display_range[0],
                                missile=dict(speed=movement['mSpeed'], authoredWidth=spec['mMissileWidth'],
                                             castRange=missile['castRange'][0], projectToCastRange=True),
                                cantCastWhileRooted=spell['cantCastWhileRooted'])
        if slot == 'r':
            require(calculations['ExplosionCalculatedDamage']['mFormulaParts'] == [
                {'mDataValue': 'ExplosionBaseDamage', '__type': 'NamedDataValueCalculationPart'},
                {'mDataValue': 'ExplosionAPRatio', '__type': 'StatByNamedDataValueCalculationPart'},
            ], 'R explosion calculation changed')
            spells[slot].update(baseDamageByRank=by_rank('ExplosionBaseDamage'),
                                abilityPowerRatio=constant('ExplosionAPRatio'),
                                slowFraction=constant('SlowPercent') / 100,
                                crowdControlSeconds=constant('CCDuration'), castRange=spell['castRange'][0],
                                authoredInnerRadius=spell['castRadius'][0],
                                authoredOuterRadius=spell['castRadiusSecondary'][0],
                                spellRevealsChampion=spell['mSpellRevealsChampion'])
            spell_audit[-1]['rawCastRadiusSecondary'] = spell['castRadiusSecondary']
            require(spell['DataValuesModeOverride']['cherry']['SpellDataValues'][0]['name'] == 'ExplosionAPRatio',
                    'R mode override changed')

    passive_path = 'Characters/Leona/Spells/LeonaSunlightPassiveAbility/LeonaSunlightPassive'
    passive = records[passive_path]['mSpell']
    parts = passive['mSpellCalculations']['TotalDamage']['mFormulaParts']
    require(len(parts) == 1 and parts[0]['__type'] == 'ByCharLevelFormulaCalculationPart',
            'Passive damage calculation changed')
    values = parts[0]['values']
    require(len(values) == 31 and values[1:19] == list(range(32, 152, 7)),
            'Passive playable-level values changed')
    duration = passive['DataValues'][0]
    require(duration['name'] == 'MarkDuration' and duration['values'] == [2.5] * 7,
            'Passive mark duration changed')
    require('1.5 seconds' in dd['passive']['description'], 'Expected stale tooltip changed')
    sunlight = dict(markSeconds=duration['values'][0], damageByLevel=values[1:19])
    audit = dict(target='PC Summoner\'s Rift 26.18', referenceVersion='16.18.8175716',
                 inputSha256=PINS, recordCount=51, statComparisons=stat_audit,
                 spells=spell_audit,
                 passive=dict(record=passive_path, formula=parts[0],
                              playableLevels='source indices 1..18; endpoints corroborated by Riot patch 14.15',
                              duration=duration, staleDataDragonDescription=dd['passive']['description']),
                 acceptance=dict(declaredValuesExported=True, playableKit=False,
                                 nativeBehaviorVerified=False, productionRosterExpanded=False))
    header = '// Generated by tools/assets/export-leona-kit.py; see docs/LEONA.md.\n'
    return {
        'src/content/leona-progression.ts': header + 'export const LEONA = ' + json.dumps(stats, indent=2) + ' as const;\n',
        'src/content/leona-spells.ts': header + 'export const LEONA_SPELLS = ' + json.dumps(spells, indent=2)
        + ' as const;\n\nexport const LEONA_SUNLIGHT = ' + json.dumps(sunlight, indent=2) + ' as const;\n',
        'docs/reference/leona/declared-values.json': json.dumps(audit, indent=2) + '\n',
    }


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = generate()
    for name, content in generated.items():
        if args.check:
            require((ROOT / name).read_bytes() == content.encode(), f'Generated file differs: {name}')
        else:
            (ROOT / name).write_text(content)
    print(('Verified' if args.check else 'Exported')
          + ' Leona stats, 18 Sunlight levels and all Q/W/E/R ranks; native behavior remains open.')
