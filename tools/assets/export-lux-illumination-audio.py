"""Ship verified, unnormalized float recordings and the source container policy."""
from pathlib import Path
import hashlib,json,subprocess

def sha(data): return hashlib.sha256(data).hexdigest()
graph_path=Path('docs/reference/lux-illumination-audio.json')
graph=json.loads(graph_path.read_text())
decoded=json.loads(Path('docs/reference/lux-illumination-audio-decoded.json').read_text())
assert decoded['sourceGraphSha256']==sha(graph_path.read_bytes())
event=graph['events'][0]
assert event['name']=='Play_sfx_Lux_LuxIlluminationPassive_hit' and event['id']==2823890895
assert event['actions']==[126980300]
nodes={n['id']:n for n in graph['nodes']}
def parameter(identity,ending):
    found=[p for p in nodes[identity]['parameters'] if p[0].endswith('/'+ending)]
    assert len(found)==1, (identity,ending,found)
    return found[0][2]
assert parameter(126980300,'idExt')=='1149'
fields=nodes[1149]['parameters']
prop=next(p for p in fields if p[0].endswith('/pID') and '[MakeUpGain]' in (p[3] or ''))
gain=float(next(p[2] for p in fields if p[0]==prop[0][:-3]+'pValue'))
assert gain==-12
assert not any('[DelayTime]' in (p[3] or '') for p in nodes[126980300]['parameters'])
policy={key:int(parameter(1149,key)) for key in [
    'eMode','eRandomMode','wAvoidRepeatCount','bResetPlayListAtEachPlay','bIsGlobal',
    'bIsContinuous','_bIsUsingWeight','u16MaxNumInstance','bKillNewest','sLoopCount','eTransitionMode']}
assert policy['eMode']==0 and policy['eRandomMode']==1
playlist=[]
for i in range(int(parameter(1149,'ulPlayListItem'))):
    sound=int(parameter(1149,f'AkPlaylistItem:{i}/ulPlayID'))
    media=int(parameter(sound,'sourceID'))
    weight=int(parameter(1149,f'AkPlaylistItem:{i}/weight'))
    item=next(m for m in decoded['media'] if m['id']==media)
    raw=(Path('.cache/lux-illumination-audio-decoded')/f'{media}.wav').read_bytes()
    assert sha(raw)==item['wavSha256']
    output=Path(f'public/assets/audio/lux-illumination-{media}.wav')
    output.parent.mkdir(parents=True,exist_ok=True);output.write_bytes(raw)
    playlist.append(dict(soundId=sound,mediaId=media,weight=weight,
        url=str(output).removeprefix('public/'),sha256=item['wavSha256'],durationSeconds=item['durationSeconds']))
assert {p['mediaId'] for p in playlist}==set(event['mediaIds'])
profile=dict(eventId=event['id'],gainDb=gain,delaySeconds=0,policy=policy,variants=playlist,
    unresolvedHierarchyIds=graph['unresolvedHierarchyIds'])
Path('src/content/lux-illumination-audio.ts').write_text(
    '// Generated by tools/assets/export-lux-illumination-audio.py.\n' +
    '// Source policy only; native random state, bus mix and runtime dispatch remain unverified.\n'+
    'export const LUX_ILLUMINATION_AUDIO = '+json.dumps(profile,indent=2)+' as const;\n')
subprocess.run(['npx','prettier','--write','src/content/lux-illumination-audio.ts'],check=True,stdout=subprocess.DEVNULL)
print(json.dumps(profile))
