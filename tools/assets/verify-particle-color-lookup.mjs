/** Generate comparison samples by executing the pinned reference implementation. */
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import ts from 'typescript';
import { execFileSync } from 'node:child_process';
const revision = '65a7d2a746b9d02d65dab788b5f7b8198d5e555e';
const files = [];
for (const name of ['enums.ts', 'colorLookup.ts', 'readVfxSystem.ts']) {
  const url = `https://raw.githubusercontent.com/LeagueToolkit/ltk-manager/${revision}/src/modules/workshop/bin/vfx/${name}`;
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${response.status} ${url}`);
  const code = await response.text();
  const cached = await readFile(`.cache/ltk-manager/src/modules/workshop/bin/vfx/${name}`, 'utf8');
  if (code !== cached) throw new Error(`Pinned source differs from inspected cache: ${name}`);
  files.push({ name, url, sha256: createHash('sha256').update(code).digest('hex'), code });
}
const compile = (code) =>
  ts.transpileModule(code, {
    compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 },
  }).outputText;
const moduleUrl = (code) => 'data:text/javascript;base64,' + Buffer.from(code).toString('base64');
const enumsUrl = moduleUrl(compile(files[0].code));
const source = compile(files[1].code).replace('from "./enums"', `from "${enumsUrl}"`);
const { colorLookupInto } = await import(moduleUrl(source));
const samples = [];
for (const type of [0, 1, 2, 3])
  for (const phase of [0, 0.17, 0.75, 1]) {
    const travel = new Float32Array([3.1, -4.2, 12.3]),
      roll = new Float32Array([0.371]);
    const emitter = {
      lookupX: type,
      lookupY: type,
      lookupScales: [0.5, -2],
      lookupOffsets: [0.2, 1.7],
    };
    const out = new Float32Array(2);
    colorLookupInto(emitter, { travel, roll }, 0, phase, out, 0);
    samples.push({
      types: [type, type],
      scales: emitter.lookupScales,
      offsets: emitter.lookupOffsets,
      phase,
      travel: [...travel],
      birthRandom: roll[0],
      expected: [...out],
    });
  }
await writeFile(
  'docs/reference/particle-color-lookup.json',
  JSON.stringify(
    {
      revision,
      files: files.map(({ code, ...metadata }) => metadata),
      samples,
      status:
        'Executed pinned ltk-manager implementation; native engine lookup/random-stream equivalence remains unverified.',
    },
    null,
    2
  ) + '\n'
);
console.log(`Verified three pinned files and generated ${samples.length} lookup comparisons.`);

const pinBytes = await readFile('docs/reference/lux-binding-target-vfx.json');
const pin = JSON.parse(pinBytes);
const profiles = pin.definition.complexEmitterDefinitionData.map((e, index) => ({
  index,
  name: e.emitterName,
  texture: e.particleColorTexture
    ? pin.textures
        .find((t) => t.path === e.particleColorTexture.toLowerCase())
        .output.replace('public/', '')
    : null,
  lookupTypes: [e.colorLookUpTypeX ?? 1, e.colorLookUpTypeY ?? 0],
  lookupScales: e.colorLookUpScales ?? [1, 1],
  lookupOffsets: e.colorLookUpOffsets ?? [0, 0],
}));
await writeFile(
  'src/content/lux-binding-target-lookups.ts',
  '// Generated by tools/assets/verify-particle-color-lookup.mjs.\n' +
    '// Source record SHA-256: ' +
    createHash('sha256').update(pinBytes).digest('hex') +
    '\n' +
    'export const LUX_BINDING_TARGET_LOOKUPS = ' +
    JSON.stringify(profiles, null, 2) +
    ' as const;\n'
);

execFileSync('npx', ['prettier', '--write', 'src/content/lux-binding-target-lookups.ts'], { stdio: 'ignore' });
