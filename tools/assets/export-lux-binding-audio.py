"""Export verified Light Binding WAVs and source event/container policies.

No native dispatch, attenuation or shared-bus interpretation is implied.
"""
from pathlib import Path
import hashlib
import json
import subprocess


def sha(raw):
    return hashlib.sha256(raw).hexdigest()


graph_path = Path('docs/reference/lux-binding-audio.json')
graph = json.loads(graph_path.read_text())
decoded = json.loads(Path('docs/reference/lux-binding-audio-decoded.json').read_text())
assert decoded['sourceGraphSha256'] == sha(graph_path.read_bytes())
nodes = {n['id']: n for n in graph['nodes']}


def parameter(identity, ending):
    found = [p for p in nodes[identity]['parameters'] if p[0].endswith('/' + ending)]
    assert len(found) == 1, (identity, ending)
    return found[0][2]


def properties(identity):
    fields = nodes[identity]['parameters']
    result = {}
    for p in fields:
        if not p[0].endswith('/pID'):
            continue
        name = p[3].split('[')[1].split(']')[0]
        assert name not in result, (identity, name)
        result[name] = float(next(v[2] for v in fields if v[0] == p[0][:-3] + 'pValue'))
    return result


containers = []
used_media = set()
for node in graph['nodes']:
    if node['type'] != 'CAkRanSeqCntr':
        continue
    identity = node['id']
    policy = {key: int(parameter(identity, key)) for key in [
        'eMode', 'eRandomMode', 'wAvoidRepeatCount', 'bResetPlayListAtEachPlay',
        'bIsGlobal', 'bIsContinuous', '_bIsUsingWeight', 'u16MaxNumInstance',
        'bKillNewest', 'sLoopCount', 'sLoopModMin', 'sLoopModMax', 'eTransitionMode']}
    transition = {key: float(parameter(identity, key)) for key in [
        'fTransitionTime', 'fTransitionTimeModMin', 'fTransitionTimeModMax']}
    playlist = []
    for i in range(int(parameter(identity, 'ulPlayListItem'))):
        sound = int(parameter(identity, f'AkPlaylistItem:{i}/ulPlayID'))
        assert nodes[sound]['type'] == 'CAkSound'
        media = int(parameter(sound, 'sourceID'))
        used_media.add(media)
        playlist.append(dict(soundId=sound, mediaId=media,
                             weight=int(parameter(identity, f'AkPlaylistItem:{i}/weight')),
                             properties=properties(sound)))
    containers.append(dict(id=identity, parentId=int(parameter(identity, 'DirectParentID')),
                           properties=properties(identity), policy=policy,
                           transition=transition, playlist=playlist))
assert len(containers) == 7
assert used_media == {m['id'] for m in graph['media']} == {m['id'] for m in decoded['media']}

events = []
for event in graph['events']:
    actions = []
    for action in event['actions']:
        identity = action['id']
        assert int(parameter(identity, 'idExt')) == action['target']
        actions.append(dict(id=identity, type=action['type'], target=action['target'],
                            actionType=int(parameter(identity, 'ulActionType')),
                            fadeCurve=int(parameter(identity, 'eFadeCurve')),
                            properties=properties(identity)))
    events.append(dict(id=event['id'], name=event['name'], actions=actions))

# Verify every payload before publishing any file.
media = []
payloads = []
for item in decoded['media']:
    identity = item['id']
    source = next(m for m in graph['media'] if m['id'] == identity)
    assert item['encodedSha256'] == source['sha256']
    raw = (Path('.cache/lux-binding-audio-decoded') / f'{identity}.wav').read_bytes()
    assert len(raw) == item['wavBytes'] and sha(raw) == item['wavSha256']
    output = Path(f'public/assets/audio/lux-binding-{identity}.wav')
    payloads.append((output, raw))
    media.append(dict(id=identity, url=str(output).removeprefix('public/'),
                      sha256=item['wavSha256'], pcmSha256=item['pcmSha256'],
                      frames=item['frames'], sampleRate=item['sampleRate'], channels=item['channels'],
                      durationSeconds=item['durationSeconds'], peak=item['peak']))
for output, raw in payloads:
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_bytes(raw)
profile = dict(events=events, containers=containers, media=media,
               unresolvedHierarchyIds=graph['unresolvedHierarchyIds'])
Path('src/content/lux-binding-audio.ts').write_text(
    '// Generated by tools/assets/export-lux-binding-audio.py.\n'
    '// Source policies only; native dispatch, attenuation and bus mix remain unverified.\n'
    'export const LUX_BINDING_AUDIO = ' + json.dumps(profile, indent=2) + ' as const;\n')
subprocess.run(['npx', 'prettier', '--write', 'src/content/lux-binding-audio.ts'], check=True,
               stdout=subprocess.DEVNULL)
print(json.dumps(dict(events=len(events), containers=len(containers), media=len(media),
                      bytes=sum(len(raw) for _, raw in payloads))))

cast_event = next(e for e in events if e['name'] == 'Play_sfx_Lux_LuxLightBinding_OnCast')
assert len(cast_event['actions']) == 1
cast_action = cast_event['actions'][0]
cast_container = next(c for c in containers if c['id'] == cast_action['target'])
assert cast_action['type'] == 'CAkActionPlay'
assert cast_container['id'] == 1151 and cast_container['policy']['sLoopCount'] == 1
cast = dict(eventId=cast_event['id'], gainDb=cast_container['properties']['MakeUpGain'],
            delaySeconds=cast_action['properties']['DelayTime'] / 1000,
            policy=cast_container['policy'],
            variants=[dict(**next(m for m in media if m['id']==p['mediaId']), soundId=p['soundId'])
                      for p in cast_container['playlist']])
assert all(not p['properties'] for p in cast_container['playlist'])
Path('src/content/lux-binding-cast-audio.ts').write_text(
    '// Generated by tools/assets/export-lux-binding-audio.py.\n'
    'export const LUX_BINDING_CAST_AUDIO = ' + json.dumps(cast, indent=2) + ' as const;\n')
subprocess.run(['npx', 'prettier', '--write', 'src/content/lux-binding-cast-audio.ts'], check=True,
               stdout=subprocess.DEVNULL)
