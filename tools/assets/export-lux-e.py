"""Generate the E source profile. --check verifies output; --verify-sources audits cached originals."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
parser.add_argument('--verify-sources', action='store_true')
args = parser.parse_args()
pin = json.loads(Path('docs/reference/lux-e.json').read_text())
ability_path = 'Characters/Lux/Spells/LuxLightStrikeKugelAbility'
records = pin['records']
ability = records[ability_path]
assert set(records) == {ability_path, *ability['mChildSpells']}
parent = records[ability['mRootSpell']]['mSpell']
toggle = records[ability_path + '/LuxLightstrikeToggle']['mSpell']
dd = pin['dataDragon']['spell']
assert 'Trait_FreeRecast' in toggle['mSpellTags']
assert toggle['mClientData']['mUseTooltipFromAnotherSpell'] == ability['mRootSpell']
assert parent['mAnimationName'] == 'Spell3'
assert parent['mMissileSpec']['movementComponent']['__type'] == 'FixedSpeedMovement'
assert parent['mMissileSpec']['movementComponent']['mTracksTarget'] is False
values = {entry['name']: entry['values'] for entry in parent['DataValues']}
formula = parent['mSpellCalculations']['TotalDamageTT']['mFormulaParts']
assert formula[0]['mDataValue'] == 'BaseDamage'
assert formula[1]['__type'] == 'StatByCoefficientCalculationPart'
assert abs(formula[1]['mCoefficient'] - parent['mCoefficient']) < 1e-7
assert values['BaseDamage'][1:6] == dd['effect'][2]
assert values['SlowPercent'][1:6] == dd['effect'][1]
assert values['SlowZoneDuration'][1:6] == dd['effect'][3]
assert parent['mana'][:5] == dd['cost']
assert parent['cooldownTime'][1:6] == dd['cooldown']
assert parent['castRange'][1:6] == dd['range']

if args.verify_sources:
    for filename, expected in [('.cache/lux-16.18.json', pin),
                               ('.cache/lux-ddragon-16.18.1.json', pin['dataDragon']),
                               ('.cache/lux-e-reference.mp4', pin['video'])]:
        raw = Path(filename).read_bytes()
        assert hashlib.sha256(raw).hexdigest() == expected['sha256'], filename
    original = json.loads(Path('.cache/lux-16.18.json').read_text())
    assert all(original[key] == record for key, record in records.items())
    assert json.loads(Path('.cache/lux-ddragon-16.18.1.json').read_text())['data']['Lux']['spells'][2] == dd

def tidy(value):
    if isinstance(value, list):
        return [tidy(v) for v in value]
    return round(value, 6) if isinstance(value, float) else value

# Unresolved geometry is retained under distinct source field names. No value is
# silently promoted into a gameplay radius or an automatic-expiry anchor.
profile = {
    'castSeconds': parent['spellCastTime'],
    'mana': parent['mana'][:5],
    'cooldownSeconds': parent['cooldownTime'][1:6],
    'baseDamage': values['BaseDamage'][1:6],
    'abilityPowerRatio': formula[1]['mCoefficient'],
    'slowPercent': values['SlowPercent'][1:6],
    'slowLingerSeconds': values['SlowLingerDuration'][1],
    'zoneSeconds': values['SlowZoneDuration'][1],
    'visionRadius': values['VisionRadius'][1],
    'castRange': parent['castRange'][1],
    'movementSpeed': parent['mMissileSpec']['movementComponent']['mSpeed'],
    'legacyMissileSpeed': parent['missileSpeed'],
    'castRadius': parent['castRadius'][1],
    'effectRadiusCandidate': parent['mEffectAmount'][3]['value'][1],
    'perceptionBubbleRadius': parent['mMissileSpec']['visibilityComponent']['mPerceptionBubbleRadius'],
}
text = ('// Generated by tools/assets/export-lux-e.py from docs/reference/lux-e.json.\n'
        '// Source profile only: geometry and callback anchors require native comparison.\n'
        'export const LUX_E_SOURCE = ' + json.dumps({k: tidy(v) for k, v in profile.items()}, indent=2) + ' as const;\n')
text = subprocess.run(['npx', 'prettier', '--stdin-filepath', 'src/content/lux-e.ts'],
                      input=text, text=True, capture_output=True, check=True).stdout
output = Path('src/content/lux-e.ts')
if args.check:
    assert output.read_text() == text, 'Lux E source profile is stale; regenerate it'
else:
    output.write_text(text)
print('Validated five E records, parent formula and Data Dragon agreement; source profile ' + ('matches' if args.check else 'written'))
