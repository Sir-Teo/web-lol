"""Export Essence Theft declarations without supplying omitted native defaults/callbacks."""
import argparse
import json
import runpy
from pathlib import Path

declarations = runpy.run_path(str(Path(__file__).with_name('export-ahri-declarations.py')))
ROOT, require = declarations['ROOT'], declarations['require']


def generate():
    pin, dd = declarations['load']()
    records = pin['records']
    root = records['Characters/Ahri/Spells/AhriPassiveAbility/AhriPassive']['mSpell']
    named = {row['name']: row['values'] for row in root['DataValues']}
    require(len(named) == 2, 'Passive named closure changed')

    def constant(name):
        raw = named[name]
        require(all(v == raw[0] for v in raw), f'Passive constant became ranked: {name}')
        return raw[0]

    heals = {}
    for name in ['ChampionHeal', 'MinionHeal']:
        parts = root['mSpellCalculations'][name]['mFormulaParts']
        require(len(parts) == 2 and parts[0]['__type'] == 'ByCharLevelInterpolationCalculationPart'
                and parts[1]['__type'] == 'StatByCoefficientCalculationPart' and 'mStat' not in parts[1],
                'Passive heal calculation/default contract changed')
        heals[name] = dict(startValue=parts[0]['mStartValue'], endValue=parts[0]['mEndValue'],
                           statCoefficient=parts[1]['mCoefficient'])
    public = dd['passive']
    require(public['name'] == 'Essence Theft' and '9 minions or monsters' in public['description']
            and 'taking down an enemy champion' in public['description'], 'Passive client intent changed')
    child = records['Characters/Ahri/Spells/AhriPassiveAbility/AhriPassiveMissile']['mSpell']
    spec = child['mMissileSpec']
    movement = spec['movementComponent']
    require(movement['__type'] == 'AcceleratingMovement'
            and [row['__type'] for row in spec['behaviors']] == ['CastOnMovementComplete', 'DestroyOnMovementComplete'],
            'Passive missile declaration changed')
    values = dict(name=public['name'], description=public['description'], icon=Path(public['image']['full']).stem,
                  maxStacks=constant('MaxStacks'), takedownWindowSeconds=constant('TakedownWindow'),
                  healCalculations=heals,
                  missile=dict(initialSpeed=movement['mInitialSpeed'], minimumSpeed=movement['mMinSpeed'],
                               maximumSpeed=movement['mMaxSpeed'], acceleration=movement['mAcceleration']),
                  genericMissileSpeed=child['missileSpeed'], legacyChildCastSeconds=child['spellCastTime'])
    return ('// Generated by tools/assets/export-ahri-passive.py; see docs/AHRI.md.\n'
            '// mStat, level-domain/curve and native kill/heal/arrival execution are not supplied.\n'
            'export const AHRI_PASSIVE = ' + json.dumps(values, indent=2, allow_nan=False) + ' as const;\n').encode()


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    declarations['publish'](generate(), ROOT / 'src/content/ahri-passive.ts', args.check)
    print('Verified Essence Theft counter/window, heal endpoints/coefficient omissions and accelerating missile declarations.')
