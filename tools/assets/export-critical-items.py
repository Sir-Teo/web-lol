"""Generate critical-damage items from the pinned current item records."""
import argparse, json, subprocess
from pathlib import Path
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
pin = json.loads(Path('docs/reference/infinity-edge.json').read_text())
items = []
for code, identity in [('1038', 'bf-sword'), ('3031', 'infinity-edge')]:
    dd, raw = pin['items'][code], pin['communityDragon']['records']['Items/'+code]
    assert dd['maps']['11'] and dd['gold']['purchasable']
    assert dd['gold']['base'] == raw['price']
    assert dd['stats']['FlatPhysicalDamageMod'] == raw['mFlatPhysicalDamageMod']
    assert dd['stats'].get('FlatCritChanceMod', 0) == raw.get('mFlatCritChanceMod', 0)
    assert dd.get('from', []) == [p.removeprefix('Items/') for p in raw.get('recipeItemLinks', [])]
    bonus = round(raw.get('mFlatCritDamageMod', 0), 6)
    if bonus: assert f'<attention>{bonus * 100:g}%</attention> Critical Strike Damage' in dd['description']
    damage = int(raw['mFlatPhysicalDamageMod']); chance = raw.get('mFlatCritChanceMod', 0)
    description = f'+{damage} Attack Damage'
    if chance: description += f' · +{chance*100:g}% Critical Strike Chance'
    if bonus: description += f' · +{bonus*100:g}% Critical Strike Damage'
    items.append(dict(id=identity, name=dd['name'], price=dd['gold']['total'], sell=dd['gold']['sell'], description=description, icon=code,
        damage=damage, criticalChance=chance, bonusCriticalDamage=bonus, armor=0, magicResist=0, abilityPower=0, hp=0, speed=0))
groups = [pin['communityDragon']['records'][key] for key in pin['communityDragon']['records']['Items/3031']['mItemGroups']]
assert sum(group.get('mMaxGroupOwnable') == 1 for group in groups) == 2
text = '// Generated by tools/assets/export-critical-items.py.\nexport const CRITICAL_ITEMS = ' + json.dumps(items, indent=2) + ' as const;\n'
text = subprocess.run(['npx', 'prettier', '--stdin-filepath', 'src/content/critical-items.ts'],input=text,text=True,capture_output=True,check=True).stdout
path = Path('src/content/critical-items.ts')
if args.check: assert path.read_text() == text, 'Critical item catalog drift'
else: path.write_text(text)
print('Verified critical item prices, stats, recipe and unique ownership groups.')
