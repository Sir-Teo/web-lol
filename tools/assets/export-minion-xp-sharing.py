"""Verify the pinned standard-mode XP sharing table and export normalized values."""
import hashlib
import json
from pathlib import Path

pin = json.loads(Path('docs/reference/minion-xp-sharing.json').read_text())
raw = Path('.cache/map11-definition.json').read_bytes()
assert hashlib.sha256(raw).hexdigest() == pin['sha256']
source = json.loads(raw)
assert source[pin['mode']]['mExperienceModData'] == pin['record']
assert source[pin['record']] == pin['data']
values = [round(n, 6) for n in pin['data']['mPlayerMinionSplitXp']]
Path('src/content/minion-xp-sharing.ts').write_text(
    '// Generated by tools/assets/export-minion-xp-sharing.py; original floats are retained in the pin.\n'
    + 'export const MINION_XP_SHARES = ' + json.dumps(values) + ' as const;\n')
