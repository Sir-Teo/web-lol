"""Export Judgment's frozen root-mode values and checked source clip mapping."""
import hashlib
import json
from pathlib import Path

pin = json.loads(Path('docs/reference/garen-character.json').read_text())
spell = pin['records']['Characters/Garen/Spells/GarenEAbility/GarenE']['mSpell']
cancel = pin['records']['Characters/Garen/Spells/GarenEAbility/GarenECancel']['mSpell']
client = json.loads(Path('docs/reference/garen-e-ddragon.json').read_text())
dd = client['spell']
assert client['version'] == '16.18.1' and dd['id'] == 'GarenE'
assert dd['maxrank'] == spell['mClientData']['mTooltipData']['mLists']['LevelUp']['levelCount'] == 5
assert spell['mTargetingTypeData']['__type'] == 'SelfAoe'
assert cancel['mTargetingTypeData']['__type'] == 'Self' and cancel['bIsToggleSpell']
assert dd['cooldown'] == spell['cooldownTime'][1:6]
assert dd['range'] == spell['castRangeDisplayOverride'][:5]
assert dd['cost'] == [0] * 5
values = {v['name']: v['values'] for v in spell['DataValues']}
assert all(len(v) == 7 for v in values.values())

def scalar(name):
    v = values[name]
    assert len(set(v)) == 1
    return v[0]

assert spell['mSpellCalculations']['TotalDamage']['mFormulaParts'] == [
    {'mDataValue': 'BaseDamagePerTick', '__type': 'NamedDataValueCalculationPart'},
    {'mStat': 2, 'mDataValue': 'ADRatioPerTick', '__type': 'StatByNamedDataValueCalculationPart'},
]
model = json.loads(Path('docs/reference/garen-model.json').read_text())
clips = model['animations']['data']['Characters/Garen/Animations/Skin0']['mClipDataMap']
assert clips['Spell3']['__type'] == 'ParametricClipData'
assert clips['Spell3']['Updater']['__type'] == 'LookAtSpellTargetAngleParametricUpdater'
assert {v['mClipName'] for v in clips['Spell3']['mParametricPairDataList']} == {
    'Spell3_-180', 'Spell3_-90', 'Spell3_0', 'Spell3_90', 'Spell3_180',
}
manifest = json.loads(Path('public/assets/models/garen-base.json').read_text())
assert hashlib.sha256(Path('public/assets/models/garen-base.glb').read_bytes()).hexdigest() == manifest['output']['sha256']
clip = next(c for c in manifest['clips'] if c['state'] == 'Spell3_0')
assert clip['source'] == model['atomicClips']['Spell3_0']
out = dict(
    baseDamageByRank=values['BaseDamagePerTick'][1:6],
    attackDamageRatioByRank=values['ADRatioPerTick'][1:6],
    cooldownSecondsByRank=dd['cooldown'],
    durationSeconds=scalar('Duration'),
    baseStrikes=int(scalar('NumTicks')),
    bonusAttackSpeedPerStrike=scalar('ASPerTick'),
    nearestEnemyBonus=scalar('NearestEnemyBonus'),
    strikesToShred=int(scalar('StacksToShred')),
    armorReduction=scalar('ShredAmount'),
    shredSeconds=scalar('ShredDuration'),
    bonusCriticalDamageRatio=scalar('CritMod'),
    radius=dd['range'][0],
    animationClip=clip['name'],
)
Path('src/content/garen-e.ts').write_text(
    '// Generated by tools/assets/export-garen-e.py; runtime policies: docs/GAREN-E.md.\n'
    'export const GAREN_E = ' + json.dumps(out, indent=2) + ' as const;\n')
print('Exported five Judgment ranks, independent scalar rules and source parametric clip foundation.')
