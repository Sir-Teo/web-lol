"""Verify authored attack glow layers and losslessly decode their source texture."""
from pathlib import Path
from io import BytesIO
import hashlib
import json
from PIL import Image
from cdtb.export import TexConverter

pin = json.loads(Path('docs/reference/ashe-arrow-glow.json').read_text())
raw = Path(pin['definitionCache']).read_bytes()
assert hashlib.sha256(raw).hexdigest() == pin['definitionSha256']
data = json.loads(raw)
result = {}
for variant, selected in pin['layers'].items():
    emitters = [e for e in data[selected['record']]['complexEmitterDefinitionData'] if e['emitterName'] in ['Glow', 'Glow1']]
    assert emitters == selected['emitters'] and len(emitters) == 2
    result[variant] = []
    for e in emitters:
        assert not e.get('disabled') and e['blendMode'] == 4
        assert e['bindWeight']['constantValue'] == 1 and e['particleIsLocalOrientation'] == 1
        assert e['texture'].lower() == pin['texture']['path']
        result[variant].append(dict(name=e['emitterName'], size=e['birthScale0']['constantValue'][:2], offset=e['SpawnShape']['emitOffset'], life=e['particleLifetime']['constantValue'], times=e['Color']['dynamics']['times'], colors=e['Color']['dynamics']['values']))
texture = Path(pin['textureCache']).read_bytes()
assert len(texture) == pin['texture']['bytes'] and hashlib.sha256(texture).hexdigest() == pin['texture']['sha256']
image = Image.open(BytesIO(TexConverter.tex_to_dds(texture))).convert('RGBA')
output = Path('public/assets/effects/ashe-arrow-glow.png')
image.save(output)
assert Image.open(output).convert('RGBA').tobytes() == image.tobytes()
Path('src/content/ashe-arrow-glow.ts').write_text('// Generated by tools/assets/export-ashe-arrow-glow.py.\nexport const ASHE_ARROW_GLOW = '+json.dumps(result,indent=2)+' as const;\n')
print('Verified four source glow emitters and exact texture pixels:', image.size)
